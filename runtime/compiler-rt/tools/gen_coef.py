#!/usr/bin/env python3
"""Generate lib/math/sf_coef.h: polynomial coefficients and the 2/pi table for lib/math/mathf.c.

Chebyshev-node interpolation in 100-digit decimal arithmetic (stdlib only), degree chosen as the
smallest whose rounded-coefficient error stays under 2^-27 relative. Run: python3 tools/gen_coef.py > lib/math/sf_coef.h
"""
import struct
from decimal import Decimal as D, getcontext
from fractions import Fraction as F

getcontext().prec = 110
TARGET = D(2) ** -27


def pi():
    def arccot(n):
        x = D(1) / n; s = x; t = x; k = 1; n2 = n * n
        while abs(t) > D(10) ** -105:
            t = -t / n2; k += 2; s += t / k
        return s
    return 4 * (4 * arccot(5) - arccot(239))


PI = pi()


def ser(term, x, n=140):
    s = D(0)
    for i in range(n):
        s += term(x, i)
    return s


def fsin(x):
    t = x; s = x
    for i in range(1, 60):
        t = -t * x * x / ((2 * i) * (2 * i + 1)); s += t
    return s


def fcos(x):
    t = D(1); s = D(1)
    for i in range(1, 60):
        t = -t * x * x / ((2 * i - 1) * (2 * i)); s += t
    return s


def fatan(x):
    t = x; s = x
    for i in range(1, 400):
        t = -t * x * x; s += t / (2 * i + 1)
    return s


def fatanh(x):
    t = x; s = x
    for i in range(1, 400):
        t = t * x * x; s += t / (2 * i + 1)
    return s


def fexp(x):
    t = D(1); s = D(1)
    for i in range(1, 80):
        t = t * x / i; s += t
    return s


def f32(v):
    return struct.unpack('<f', struct.pack('<f', float(v)))[0]


def fit(h, a, b, deg):
    """Interpolate h at Chebyshev nodes on [a, b]; monomial coefficients as Fractions."""
    import math
    n = deg + 1
    xs = [(D(a) + D(b)) / 2 + (D(b) - D(a)) / 2 * D(math.cos(math.pi * (2 * k + 1) / (2 * n))) for k in range(n)]
    A = [[F(x) ** j for j in range(n)] + [F(h(x))] for x in xs]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(A[r][c])); A[c], A[p] = A[p], A[c]
        for r in range(n):
            if r != c:
                f = A[r][c] / A[c][c]
                A[r] = [u - f * v for u, v in zip(A[r], A[c])]
    return [A[i][n] / A[i][i] for i in range(n)]


def maxerr(h, coefs, a, b, scale):
    worst = D(0)
    for k in range(1, 401):
        x = D(a) + (D(b) - D(a)) * k / 400
        p = D(0)
        for c in reversed(coefs):
            p = p * x + D(c)
        e = abs(p - h(x)) * scale(x)
        worst = max(worst, e)
    return worst


def best(name, h, a, b, scale, degs=range(1, 12)):
    for d in degs:
        c = fit(h, a, b, d)
        r = [D(f32(float(x))) for x in c]
        if maxerr(h, r, a, b, scale) < TARGET:
            return name, [f32(float(x)) for x in c]
    raise SystemExit('no degree for ' + name)


def lit(v):
    return ('%.9g' % v) + 'f'


out = ['/* Generated by tools/gen_coef.py; do not edit. */', '#ifndef SF_COEF_H', '#define SF_COEF_H', '']
def emit(name, coefs):
    out.append('#define %s_N %d' % (name, len(coefs)))
    out.append('static const float %s[%s_N] = { %s };' % (name, name, ', '.join(lit(c) for c in coefs)))

PIO4 = PI / 4
Z = PIO4 ** 2
z0 = D(10) ** -9
# sin x = x + x^3 P(x^2); relative error = z * err(P)
emit(*best('SIN_P', lambda z: (fsin(z.sqrt()) - z.sqrt()) / (z * z.sqrt()), z0, Z, lambda z: z))
# cos x = 1 - z/2 + z^2 Q(z)
emit(*best('COS_P', lambda z: (fcos(z.sqrt()) - 1 + z / 2) / (z * z), z0, Z, lambda z: z * z))
# tan x = x + x^3 T(z)
ft = lambda z: (fsin(z.sqrt()) / fcos(z.sqrt()) - z.sqrt()) / (z * z.sqrt())
emit(*best('TAN_P', ft, z0, Z, lambda z: z, range(1, 14)))
# atan x = x + x^3 A(z) on |x| <= tan(pi/8)
T8 = fsin(PI / 8) / fcos(PI / 8)
emit(*best('ATAN_P', lambda z: (fatan(z.sqrt()) - z.sqrt()) / (z * z.sqrt()), z0, T8 ** 2, lambda z: z))
# exp r = 1 + r + r^2 E(r), |r| <= ln2/2
LN2 = (D(2)).ln()
emit(*best('EXP_P', lambda r: (fexp(r) - 1 - r) / (r * r), -LN2 / 2, LN2 / 2, lambda r: r * r))
# log(1+f) = f - hfsq + s (hfsq + R), R = z * L(z), z = s^2, s = f/(2+f)
SM = (D(2).sqrt() - 1) / (D(2).sqrt() + 1)
emit(*best('LOG_P', lambda z: (2 * fatanh(z.sqrt()) / z.sqrt() - 2) / z, z0, SM ** 2, lambda z: z * z * 2 / 3 * 0 + z))

def split(v, bits):
    """v rounded to `bits` significant bits, then the float32 remainder."""
    import math
    m, e = math.frexp(float(v))
    hi = math.ldexp(round(m * 2 ** bits), e - bits)
    return f32(hi), f32(float(v - D(hi)))

p1, _ = split(PI / 2, 17); r1 = PI / 2 - D(p1)
p2, _ = split(r1, 17); r2 = r1 - D(p2)
p3 = f32(float(r2))
l1, _ = split(LN2, 16); l2 = f32(float(LN2 - D(l1)))
out += ['#define PIO2_1 ' + lit(p1), '#define PIO2_2 ' + lit(p2), '#define PIO2_3 ' + lit(p3),
        '#define TWO_OVER_PI ' + lit(f32(float(2 / PI))), '#define PIO2_HI ' + lit(f32(float(PI / 2))),
        '#define PIO2_LO ' + lit(f32(float(PI / 2 - D(f32(float(PI / 2)))))),
        '#define PIO4_HI ' + lit(f32(float(PI / 4))), '#define PI_HI ' + lit(f32(float(PI))),
        '#define PI_LO ' + lit(f32(float(PI - D(f32(float(PI)))))),
        '#define LN2_1 ' + lit(l1), '#define LN2_2 ' + lit(l2), '#define LOG2E ' + lit(f32(float(1 / LN2))),
        '#define LOG10E ' + lit(f32(float(1 / D(10).ln()))), '#define TAN_PI_8 ' + lit(f32(float(T8))),
        '#define TAN_3PI_8 ' + lit(f32(float(fsin(3 * PI / 8) / fcos(3 * PI / 8)))), '']
# 2/pi as 32-bit words, most significant first: word i holds bits 32i+1 .. 32i+32 after the point.
N = 10
bits = int((2 / PI) * (D(2) ** (32 * N)))
words = [(bits >> (32 * (N - 1 - i))) & 0xFFFFFFFF for i in range(N)]
out.append('#define TWO_OVER_PI_WORDS %d' % N)
out.append('static const uint32_t two_over_pi[TWO_OVER_PI_WORDS] = {\n    ' + ',\n    '.join('0x%08Xu' % w for w in words) + ',\n};')
out += ['', '#endif']
print('\n'.join(out))
