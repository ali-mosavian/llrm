/* Host side of the f64 target runs: writes vectors64.h with expected results from the host FPU.
 * cc -O2 -ffp-contract=off tests/gen_vectors64.c -o gen64 && ./gen64 [n] > vectors64.h */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static uint64_t rng = 0x9E3779B97F4A7C15ull;
static uint64_t rnd(void)
{
    rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17;
    return rng * 0x2545F4914F6CDD1Dull;
}

static uint64_t edge[] = {
    0x0000000000000000ull, 0x8000000000000000ull, 1, 0x8000000000000001ull, 0x000FFFFFFFFFFFFFull, 0x0010000000000000ull,
    0x0010000000000001ull, 0x3FF0000000000000ull, 0xBFF0000000000000ull, 0x3FF0000000000001ull, 0x3FEFFFFFFFFFFFFFull,
    0x4000000000000000ull, 0x7FEFFFFFFFFFFFFFull, 0xFFEFFFFFFFFFFFFFull, 0x7FF0000000000000ull, 0xFFF0000000000000ull,
    0x7FF8000000000000ull, 0x7FF0000000000001ull, 0xFFF8000000000001ull, 0x4330000000000000ull, 0x433FFFFFFFFFFFFFull,
    0x43E0000000000000ull, 0xC3E0000000000000ull, 0x41E0000000000000ull, 0xC1E0000000000000ull, 0x3FE0000000000000ull,
    0x3CA0000000000000ull, 0x7FD0000000000000ull, 0x0020000000000000ull, 0x400921FB54442D18ull,
};
#define NEDGE (sizeof edge / sizeof edge[0])
static uint64_t gen(void)
{
    uint64_t r = rnd();
    switch (r & 7) {
    case 0: return edge[(r >> 8) % NEDGE];
    case 1: return rnd() & 0x800FFFFFFFFFFFFFull;
    case 2: return (rnd() & 0x800FFFFFFFFFFFFFull) | ((uint64_t)(1000 + (rnd() & 0x3F)) << 52);
    case 3: return edge[(r >> 8) % NEDGE] + (rnd() & 7) - 3;
    default: return rnd();
    }
}

static double b2d(uint64_t b) { double d; memcpy(&d, &b, 8); return d; }
static uint64_t d2b(double d) { uint64_t b; memcpy(&b, &d, 8); return b; }
#define W(v) (unsigned)((v) >> 32), (unsigned)(v)
int main(int argc, char **argv)
{
    int n = argc > 1 ? atoi(argv[1]) : 3000;
    printf("/* generated by tests/gen_vectors64.c */\n#define NV %d\n", n);
    printf("static const uint32_t V[NV][16] = { /* a, b, add, sub, mul, div (hi,lo each), cmp, floatsidf(a.lo) (hi,lo), fixdfsi(a) */\n");
    for (int i = 0; i < n; i++) {
        uint64_t a = gen(), b = gen();
        volatile double x = b2d(a), y = b2d(b);
        int cmp = x < y ? -1 : x > y ? 1 : x == y ? 0 : 2;
        volatile double fi = (double)(int32_t)(uint32_t)a;
        int ok = x > -2147483649.0 && x < 2147483648.0;
        uint64_t r[6] = {a, b, d2b(x + y), d2b(x - y), d2b(x * y), d2b(x / y)};
        printf("  {");
        for (int k = 0; k < 6; k++) printf("0x%08Xu,0x%08Xu,", W(r[k]));
        printf("%d,0x%08Xu,0x%08Xu,0x%08Xu},\n", cmp, W(d2b(fi)), ok ? (uint32_t)(int32_t)x : 0xDEADBEEFu);
    }
    printf("};\n");
    return 0;
}
