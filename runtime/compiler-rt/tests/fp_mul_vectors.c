/* Host generator: f32 and f64 multiply, divide and int-to-float vectors from the host FPU. Prints a C header; op 0/1 = mul f32/f64, 2/3 = div f32/f64, 4/5 = floatsisf/floatsidf (a = int32), 6 = floatdidf (a = int64). Operand bits: 1/8 denormal each, so the normalise (clz) path is exercised. No NaN results (their payload is tested by host_f32.c / host_f64.c). */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
static uint64_t s = 0x9E3779B97F4A7C15ull;
static uint64_t rnd(void) { s ^= s << 13; s ^= s >> 7; s ^= s << 17; return s; }
static uint64_t pick(int dbl)
{
    unsigned mb = dbl ? 52 : 23, eb = dbl ? 11 : 8, emax = (1u << eb) - 1, bias = emax >> 1, k = rnd() % 8, e;
    uint64_t man = rnd() & ((1ull << mb) - 1), sign = rnd() & 1;
    switch (k) {
    case 0: e = 0; break;
    case 1: e = emax; man = 0; break;
    case 2: e = emax - 1; break;
    case 3: e = 1; break;
    default: e = bias - 20 + rnd() % 40; break;
    }
    return sign << (mb + eb) | (uint64_t)e << mb | man;
}
int main(int argc, char **argv)
{
    int n = argc > 1 ? atoi(argv[1]) : 4000;
    printf("/* generated by tests/fp_mul_vectors.c */\nstruct vec { int op; unsigned long long a, b, want; };\nstatic const struct vec V[] = {\n");
    for (int i = 0; i < n; i++) for (int op = 0; op < 7; op++) {
        int dbl = op & 1, isdiv = op == 2 || op == 3, isint = op >= 4;
        uint64_t a = pick(dbl), b = pick(dbl), w;
        if (op == 6) dbl = 1;
        if (isint) { a = rnd() >> (rnd() % 64); if (rnd() & 1) a = 0ull - a; if (op != 6) a = (uint32_t)a; b = 0; }
        if (isint) {
            if (op == 4) { float r = (float)(int32_t)a; uint32_t u; memcpy(&u, &r, 4); w = u; }
            else if (op == 5) { double r = (double)(int32_t)a; memcpy(&w, &r, 8); }
            else { double r = (double)(int64_t)a; memcpy(&w, &r, 8); }
        } else if (!dbl) { uint32_t x = (uint32_t)a, y = (uint32_t)b; float fx, fy; memcpy(&fx, &x, 4); memcpy(&fy, &y, 4); volatile float vy = fy; float r = isdiv ? fx / vy : fx * vy; uint32_t u; memcpy(&u, &r, 4); w = u; if ((u & 0x7F800000) == 0x7F800000 && (u & 0x7FFFFF)) continue; }
        else { double fx, fy; memcpy(&fx, &a, 8); memcpy(&fy, &b, 8); volatile double vy = fy; double r = isdiv ? fx / vy : fx * vy; memcpy(&w, &r, 8); if ((w >> 52 & 0x7FF) == 0x7FF && (w & ((1ull << 52) - 1))) continue; }
        printf("{%d,0x%llxull,0x%llxull,0x%llxull},\n", op, (unsigned long long)a, (unsigned long long)b, (unsigned long long)w);
    }
    printf("};\n");
    return 0;
}
