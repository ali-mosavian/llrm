#!/bin/bash
# usage: [SF_CFG=x86_m32] tests/x86_conv_kernels.sh [NV] -> kernels x_sf_{f2i,f2u,i2f,u2f} (ours), x_crt_{f2i,f2u,i2f,u2f} (compiler-rt) and x_base_* (the loop alone, to subtract) in
# crates/target/llrm-x86-m32/vsgcc/kernels/ for harness.py (486-table instructions and clocks, llrm/gcc/clang variants). Float inputs of magnitude >= 2^31 or NaN are
# skipped for the float-to-int ones (C leaves them undefined and the libraries differ).
set -e
cd "$(dirname "$0")/.."
NV=${1:-400}; SF_CFG=${SF_CFG-x86_m32}; [ -n "$SF_CFG" ] && SF_CFG=$(sed -E 's/\buint(32|64)_t\b/sfu\1/g' config/$SF_CFG/config.h); export SF_CFG
K=$(cd ../../crates/target/llrm-x86-m32/vsgcc/kernels && pwd); T=$(mktemp -d); trap 'rm -r $T' EXIT
CRT=${COMPILER_RT:-$HOME/scratch/llvm-src-m16/compiler-rt/lib/builtins}
cc -O2 -ffp-contract=off tests/gen_vectors.c -o $T/gen && $T/gen $NV > $T/vectors.h
printf '#include <stdio.h>\nvoid report(long v) { printf("%%ld\\n", v); }\n' > $T/rep.c
TYPES='typedef unsigned char sfu8; typedef signed char sfi8; typedef short sfi16; typedef unsigned short sfu16; typedef int sfi32; typedef unsigned int sfu32; typedef unsigned long long sfu64; typedef long long sfi64;'
emit() { # name, call expression on (a), body already in $T/body.c
  n=$1; mkdir -p $K/$n
  { echo 'extern void report(long value);'; cat $T/body.c; sed 's/uint32_t/sfu32/' $T/vectors.h
    echo "long bench_$n(long n) { long i; sfu32 acc = 0; for (i = 0; i < n; ++i) { sfu32 a = V[i % NV][0]; acc += (sfu32)($2); } return (long)acc; }"
    echo "int main(void) { report(bench_$n($NV)); return 0; }"; } > $K/$n/$n.c
  gcc -m32 -O0 -w $K/$n/$n.c $T/rep.c -o $T/ref && $T/ref > $K/$n/$n.out
}
# ours: only the operation's own file, as linked (one operation per object); a flattened library would share and outline helpers no linked program does
for row in 'f2i|fix_si|fixsfsi|__fixsfsi|(NAN_(a)||BIG_(a)?0:__fixsfsi(a))' 'f2u|fix_usi|fixunssfsi|__fixunssfsi|(NAN_(a)||BIG_(a)?0:__fixunssfsi(a))' 'i2f|float_si|floatsisf|__floatsisf|__floatsisf((sfi32)a)' 'u2f|float_usi|floatunsisf|__floatunsisf|__floatunsisf(a)'; do
  IFS='|' read -r op file crtsrc sym call <<<"$row"
  # ours
  files=lib/fp/f32/$file.c; [ -z "$SF_CONV_FLAT" ] || files=$(tests/fp_sources.sh f32)
  { echo "/* x_sf_$op: runtime/compiler-rt $sym over $NV vectors; generated by tests/x86_conv_kernels.sh */"; echo "$TYPES"
    echo '#define UINT32_C(x) x##u'; echo '#define UINT64_C(x) x##ull'; echo '#define INT32_MAX 2147483647'; echo '#define INT32_MIN (-2147483647-1)'; echo '#define UINT32_MAX 4294967295u'
    for f in include/softfloat.h include/sf_helpers.h $files; do
      python3 tests/flatten.py $f | sed -E '/#include <(stdint|stddef|limits)\.h>/d; /#include "(softfloat|sf_helpers|sf_int)\.h"/d; s/\buint8_t\b/sfu8/g; s/\bint8_t\b/sfi8/g; s/\buint16_t\b/sfu16/g; s/\bint16_t\b/sfi16/g; s/\buint32_t\b/sfu32/g; s/\bint32_t\b/sfi32/g; s/\buint64_t\b/sfu64/g; s/\bint64_t\b/sfi64/g'
    done | awk 'BEGIN{print "#define SF_INTABI 1"; if (ENVIRON["SF_CFG"]) print ENVIRON["SF_CFG"]} {print}'
    echo '#define NAN_(a) ((((a) >> 23) & 0xFF) == 0xFF && ((a) & 0x7FFFFF))'; echo '#define BIG_(a) ((((a) >> 23) & 0xFF) >= 158)'; } > $T/body.c
  emit x_sf_$op "$call"
  # guard: the kernel holds this operation alone. A flattened library shares and outlines helpers (from_mag, sf_shr_sticky32 called): -Os floatsisf/floatunsisf read
  # +5.9% / +16.7% instructions against compiler-rt when linked they are 8% / 6% better.
  defs=$(grep -cE '^[A-Za-z_0-9 ]+ SF_NAME\([a-z0-9_]+\)\(' $K/x_sf_$op/x_sf_$op.c || true)
  [ "$defs" = 1 ] || { echo "x_sf_$op: $defs entry points in the kernel, want exactly 1 (one operation per object, as linked)" >&2; exit 1; }
  # compiler-rt, preprocessed (float typed: the call goes through a union)
  { gcc -m32 -E -P -I$CRT $CRT/$crtsrc.c | sed '/Qcomplex/d; /__alias__/d'
    echo 'int __fe_raise_inexact(void) { return 0; }'; echo 'int __fe_getround(void) { return 0; }'
    echo "typedef unsigned int sfu32; typedef int sfi32; static float u2f(sfu32 u) { union { sfu32 u; float f; } x; x.u = u; return x.f; }"
    echo '#define NAN_(a) ((((a) >> 23) & 0xFF) == 0xFF && ((a) & 0x7FFFFF))'; echo '#define BIG_(a) ((((a) >> 23) & 0xFF) >= 158)'; } > $T/body.c
  case $op in f2i|f2u) c="(NAN_(a)||BIG_(a)?0:$sym(u2f(a)))";; i2f) c="({ union { float f; sfu32 u; } r; r.f = $sym((sfi32)a); r.u; })";; u2f) c="({ union { float f; sfu32 u; } r; r.f = $sym(a); r.u; })";; esac
  emit x_crt_$op "$c"
  # the loop alone (same vectors, same guards): what each compiler's loop costs, to subtract
  { echo "$TYPES"; echo '#define NAN_(a) ((((a) >> 23) & 0xFF) == 0xFF && ((a) & 0x7FFFFF))'; echo '#define BIG_(a) ((((a) >> 23) & 0xFF) >= 158)'; } > $T/body.c
  case $op in f2i|f2u) c="(NAN_(a)||BIG_(a)?0:a)";; *) c="a";; esac
  emit x_base_$op "$c"
done
echo "wrote $K/x_{sf,crt,base}_{f2i,f2u,i2f,u2f}"
