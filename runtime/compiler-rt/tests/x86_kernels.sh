#!/bin/bash
# usage: [SF_CFG=x86_m32] tests/x86_kernels.sh [NV] -> kernels x_sf_add x_sf_sub x_sf_mul x_sf_div (ours, SF_INTABI, flattened to one freestanding file) in
# crates/target/llrm-x86-m32/vsgcc/kernels/, for harness.py (486-table clocks, llrm/gcc/clang variants). NV vectors from tests/gen_vectors.c.
set -e
cd "$(dirname "$0")/.."
NV=${1:-400}; SF_CFG=${SF_CFG-}; [ -n "$SF_CFG" ] && SF_CFG=$(sed -E 's/\buint(32|64)_t\b/sfu\1/g' config/$SF_CFG/config.h); export SF_CFG; K=$(cd ../../crates/target/llrm-x86-m32/vsgcc/kernels && pwd); T=$(mktemp -d); trap 'rm -r $T' EXIT
cc -O2 -ffp-contract=off tests/gen_vectors.c -o $T/gen && $T/gen $NV > $T/vectors.h
for op in add sub mul div; do
  n=x_sf_$op; mkdir -p $K/$n
  { echo "/* $n: runtime/compiler-rt sf32.c under -DSF_INTABI over $NV vectors; generated by tests/x86_kernels.sh */"
    echo 'extern void report(long value);'
    echo 'typedef unsigned char sfu8; typedef signed char sfi8; typedef short sfi16; typedef unsigned short sfu16; typedef int sfi32; typedef unsigned int sfu32; typedef unsigned long long sfu64; typedef long long sfi64;'
    echo '#define UINT32_C(x) x##u'; echo '#define UINT64_C(x) x##ull'; echo '#define INT32_MAX 2147483647'; echo '#define INT32_MIN (-2147483647-1)'; echo '#define UINT32_MAX 4294967295u'
    # flatten: our headers and sf32.c, without libc (the types above stand in for <stdint.h>)
    for f in include/softfloat.h include/sf_helpers.h lib/fp/sf32.c lib/fp/sf32_conv.c; do
      awk -f tests/inline_inc.awk $f | sed -E '/#include <(stdint|stddef|limits)\.h>/d; /#include "(softfloat|sf_helpers|sf_int)\.h"/d; s/\buint8_t\b/sfu8/g; s/\bint8_t\b/sfi8/g; s/\buint16_t\b/sfu16/g; s/\bint16_t\b/sfi16/g; s/\buint32_t\b/sfu32/g; s/\bint32_t\b/sfi32/g; s/\buint64_t\b/sfu64/g; s/\bint64_t\b/sfi64/g'
    done | awk 'BEGIN{print "#define SF_INTABI 1"; if (ENVIRON["SF_CFG"]) print ENVIRON["SF_CFG"]} {print}'
    cat $T/vectors.h | sed 's/uint32_t/sfu32/'
    echo "sfu32 __${op}sf3(sfu32, sfu32);"
    echo "long bench_$n(long n) { long i; sfu32 acc = 0; for (i = 0; i < n; ++i) acc += __${op}sf3(V[i % NV][0], V[i % NV][1]); return (long)acc; }"
    echo "int main(void) { report(bench_$n($NV)); return 0; }"
  } > $K/$n/$n.c
  # expected report() value: the same file built and run natively at -O0 (the harness compares every compiler with it)
  printf '#include <stdio.h>\nvoid report(long v) { printf("%%ld\\n", v); }\n' > $T/rep.c
  gcc -m32 -O0 -w $K/$n/$n.c $T/rep.c -o $T/ref_$op && $T/ref_$op > $K/$n/$n.out
done
echo "wrote $K/x_sf_{add,sub,mul,div}"
