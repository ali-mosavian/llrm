/* Host side of the target runs: writes vectors.h with expected results from the host FPU.
 * cc -O2 -ffp-contract=off tests/gen_vectors.c -o gen && ./gen [n] > vectors.h */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static uint64_t rng = 0x9E3779B97F4A7C15ull;
static uint32_t rnd(void) { rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; return (uint32_t)(rng >> 16); }
static float b2f(uint32_t b) { float f; memcpy(&f, &b, 4); return f; }
static uint32_t f2b(float f) { uint32_t b; memcpy(&b, &f, 4); return b; }
static const uint32_t edge[] = {0, 0x80000000, 1, 0x80000001, 0x7FFFFF, 0x800000, 0x800001, 0x3F800000, 0xBF800000, 0x3F800001,
    0x3F7FFFFF, 0x40000000, 0x7F7FFFFF, 0xFF7FFFFF, 0x7F800000, 0xFF800000, 0x7FC00000, 0x4B000000, 0x4B7FFFFF, 0x4F000000,
    0xCF000000, 0x3F000000, 0x34000000, 0x7E800000, 0x01000000, 0x40490FDB};
static uint32_t gen(void)
{
    uint32_t r = rnd();
    switch (r & 7) {
    case 0: return edge[(r >> 8) % (sizeof edge / sizeof *edge)];
    case 1: return rnd() & 0x807FFFFFu;
    case 2: return (rnd() & 0x80000000u) | (rnd() & 0x7FFFFFu) | ((100 + (rnd() & 0x3F)) << 23);
    default: return rnd();
    }
}
int main(int argc, char **argv)
{
    int n = argc > 1 ? atoi(argv[1]) : 3000;
    printf("/* generated by tests/gen_vectors.c */\n#define NV %d\n", n);
    printf("static const uint32_t V[NV][11] = { /* a, b, add, sub, mul, div, cmp, i2f(a), u2f(a), f2i(a), f2u(a) */\n");
    for (int i = 0; i < n; i++) {
        uint32_t a = gen(), b = gen();
        volatile float x = b2f(a), y = b2f(b);
        int cmp = x < y ? -1 : x > y ? 1 : x == y ? 0 : 2;
        volatile float fi = (float)(int32_t)a, fu = (float)a;
        uint32_t i2i = (x > -2147483648.0f && x < 2147483648.0f) ? (uint32_t)(int32_t)x : 0;
        uint32_t f2u = (x > -1.0f && x < 4294967296.0f) ? (uint32_t)x : 0;
        int ok_i = x > -2147483648.0f && x < 2147483648.0f, ok_u = x > -1.0f && x < 4294967296.0f;
        printf("  {0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu,%d,0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu},\n", a, b, f2b(x + y), f2b(x - y),
               f2b(x * y), f2b(x / y), cmp, f2b(fi), f2b(fu), ok_i ? i2i : 0xDEADBEEFu, ok_u ? f2u : 0xDEADBEEFu);
    }
    printf("};\n");
    return 0;
}
