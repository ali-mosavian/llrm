/* Host generator: binary128 vectors from libgcc's tf routines (x86-64 __float128). Prints a C header: struct { op; a; b; want } rows, 128-bit values as {lo, hi}. No NaN operands (payload rules are tested by host_f128.c). */
#include <stdio.h>
#include <stdlib.h>
#include <stdint.h>
#include <string.h>
typedef unsigned __int128 u128;
typedef __float128 q;
static uint64_t s = 0x9E3779B97F4A7C15ull;
static uint64_t rnd(void) { s ^= s << 13; s ^= s >> 7; s ^= s << 17; return s; }
static u128 pick(void)
{
    u128 sign = (u128)(rnd() & 1) << 127, man = ((u128)rnd() << 64 | rnd()) & (((u128)1 << 112) - 1);
    unsigned k = rnd() % 8, e;
    switch (k) {
    case 0: e = 0; break;                       /* zero / denormal */
    case 1: e = 0x7FFF; man = 0; break;         /* infinity */
    case 2: e = 0x7FFE; break;                  /* largest binade */
    case 3: e = 1; break;                       /* smallest normal binade */
    default: e = 0x3FFF - 40 + rnd() % 80; break;
    }
    return sign | (u128)e << 112 | man;
}
static void pr(u128 v) { printf("{0x%016llxull,0x%016llxull}", (unsigned long long)v, (unsigned long long)(v >> 64)); }
int main(int argc, char **argv)
{
    int n = argc > 1 ? atoi(argv[1]) : 2000;
    printf("/* generated by tests/f128_vectors.c */\ntypedef struct { unsigned long long lo, hi; } v128;\nstruct vec { int op; v128 a, b, want; };\nstatic const struct vec V[] = {\n");
    for (int i = 0; i < n; i++) {
        u128 a = pick(), b = pick(); q x, y, r; memcpy(&x, &a, 16); memcpy(&y, &b, 16);
        for (int op = 0; op < 4; op++) {
            volatile q vy = y;
            r = op == 0 ? x + vy : op == 1 ? x - vy : op == 2 ? x * vy : x / vy;
            u128 w; memcpy(&w, &r, 16);
            if ((w >> 112 & 0x7FFF) == 0x7FFF && (w & (((u128)1 << 112) - 1))) continue;   /* NaN result: payload is tested elsewhere */
            printf("{%d,", op); pr(a); printf(","); pr(b); printf(","); pr(w); printf("},\n");
        }
    }
    printf("};\n");
    return 0;
}
