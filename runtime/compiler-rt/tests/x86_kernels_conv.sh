#!/bin/bash
# usage: [SF_CFG=x86_m32] tests/x86_kernels_conv.sh [NV] -> kernels x_{sf,crt,sfp}_{cmp,floatsi,fixsi}: binary32 compare (__lesf2), int to float and float to int, ours / compiler-rt
# / libgcc soft-fp over the vectors of tests/gen_vectors.c, in crates/target/llrm-x86-m32/vsgcc/kernels/. Their .out must agree: the same function.
set -e
cd "$(dirname "$0")/.."
NV=${1:-400}; SF_CFG=${SF_CFG-}; [ -n "$SF_CFG" ] && SF_CFG=$(sed -E 's/\buint(32|64)_t\b/sfu\1/g' config/$SF_CFG/config.h); export SF_CFG
K=$(cd ../../crates/target/llrm-x86-m32/vsgcc/kernels && pwd); T=$(mktemp -d); trap 'rm -r $T' EXIT
P=/opt/llrm-pin/bin/clang; CRT=${COMPILER_RT:-$HOME/scratch/llvm-src-m16/compiler-rt/lib/builtins}; S=${LIBGCC_SRC:-$HOME/scratch/sf-libgcc-src/libgcc}
cc -O2 -ffp-contract=off tests/gen_vectors.c -o $T/gen && $T/gen $NV > $T/vectors.h
printf '#include <stdio.h>\nvoid report(long v) { printf("%%ld\\n", v); }\n' > $T/rep.c
TYPES='typedef unsigned char sfu8; typedef signed char sfi8; typedef short sfi16; typedef unsigned short sfu16; typedef int sfi32; typedef unsigned int sfu32; typedef unsigned long long sfu64; typedef long long sfi64;'
FLOATIO='static float u2f(unsigned int u) { union { unsigned int u; float f; } x; x.u = u; return x.f; } static unsigned int f2u(float f) { union { unsigned int u; float f; } x; x.f = f; return x.u; }'
# op: ours/crt/libgcc source file stem, the C function, ours prototype, and the loop body for each flavour (u = ours, bit patterns; f = float typed)
declare -A FN=([cmp]=lesf2 [floatsi]=floatsisf [fixsi]=fixsfsi)
declare -A CRTF=([cmp]=comparesf2 [floatsi]=floatsisf [fixsi]=fixsfsi)
declare -A SFPF=([cmp]=lesf2 [floatsi]=floatsisf [fixsi]=fixsfsi)
declare -A OURS_PROTO=([cmp]='int __lesf2(sfu32, sfu32);' [floatsi]='sfu32 __floatsisf(sfi32);' [fixsi]='sfi32 __fixsfsi(sfu32);')
declare -A OURS_BODY=([cmp]='acc += __lesf2(V[i % NV][0], V[i % NV][1]) > 0;' [floatsi]='acc += __floatsisf((sfi32)V[i % NV][0]);' [fixsi]='if (V[i % NV][9] != 0xDEADBEEFu) acc += (sfu32)__fixsfsi(V[i % NV][0]);')
declare -A F_BODY=([cmp]='acc += vfp(u2f(V[i % NV][0]), u2f(V[i % NV][1])) > 0;' [floatsi]='acc += f2u(vfp((int)V[i % NV][0]));' [fixsi]='if (V[i % NV][9] != 0xDEADBEEFu) acc += (unsigned int)vfp(u2f(V[i % NV][0]));')
for op in cmp floatsi fixsi; do
  fn=${FN[$op]}
  n=x_sf_$op; mkdir -p $K/$n
  { echo "/* $n: runtime/compiler-rt lib/fp/f32 under -DSF_INTABI over $NV vectors; generated by tests/x86_kernels_conv.sh */"
    echo 'extern void report(long value);'; echo "$TYPES"
    echo '#define UINT32_C(x) x##u'; echo '#define UINT64_C(x) x##ull'; echo '#define INT32_MAX 2147483647'; echo '#define INT32_MIN (-2147483647-1)'; echo '#define UINT32_MAX 4294967295u'
    for f in include/softfloat.h include/sf_helpers.h $(tests/fp_sources.sh f32); do
      python3 tests/flatten.py $f | sed -E '/#include <(stdint|stddef|limits)\.h>/d; /#include "(softfloat|sf_helpers|sf_int)\.h"/d; s/\buint8_t\b/sfu8/g; s/\bint8_t\b/sfi8/g; s/\buint16_t\b/sfu16/g; s/\bint16_t\b/sfi16/g; s/\buint32_t\b/sfu32/g; s/\bint32_t\b/sfi32/g; s/\buint64_t\b/sfu64/g; s/\bint64_t\b/sfi64/g'
    done | awk 'BEGIN{print "#define SF_INTABI 1"; if (ENVIRON["SF_CFG"]) print ENVIRON["SF_CFG"]} {print}'
    sed 's/uint32_t/sfu32/' $T/vectors.h
    echo "${OURS_PROTO[$op]}"
    echo "long bench_$n(long n) { long i; sfu32 acc = 0; for (i = 0; i < n; ++i) { ${OURS_BODY[$op]} } return (long)acc; }"
    echo "int main(void) { report(bench_$n($NV)); return 0; }"; } > $K/$n/$n.c
  gcc -m32 -O0 -w $K/$n/$n.c $T/rep.c -o $T/r_$n && $T/r_$n > $K/$n/$n.out
  n=x_crt_$op; mkdir -p $K/$n
  { echo 'extern void report(long value);'
    $P -ffreestanding -m32 -E -P -I$CRT $CRT/${CRTF[$op]}.c | sed '/Qcomplex/d; /__alias__/d'
    echo 'int __fe_getround(void) { return 0; }'; echo 'int __fe_raise_inexact(void) { return 0; }'
    sed 's/uint32_t/unsigned int/' $T/vectors.h; echo "$FLOATIO"
    echo "static __typeof__(__$fn) *volatile vfp = __$fn; /* a call, as a library user pays it: gcc inlines a one-TU function into the loop */"
    echo "long bench_$n(long n) { long i; unsigned int acc = 0; for (i = 0; i < n; ++i) { ${F_BODY[$op]} } return (long)acc; }"
    echo "int main(void) { report(bench_$n($NV)); return 0; }"; } > $K/$n/$n.c
  gcc -m32 -O0 -w $K/$n/$n.c $T/rep.c -o $T/r_$n && $T/r_$n > $K/$n/$n.out
  n=x_sfp_$op; mkdir -p $K/$n
  { echo 'extern void report(long value);'
    gcc -m32 -E -P -I$S/soft-fp -I$S/config/i386 -I$S -I$S/../include $S/soft-fp/${SFPF[$op]}.c
    echo 'void __sfp_handle_exceptions(int x) { (void)x; }'
    sed 's/uint32_t/unsigned int/' $T/vectors.h; echo "$FLOATIO"
    echo "static __typeof__(__$fn) *volatile vfp = __$fn; /* a call, as a library user pays it: gcc inlines a one-TU function into the loop */"
    echo "long bench_$n(long n) { long i; unsigned int acc = 0; for (i = 0; i < n; ++i) { ${F_BODY[$op]} } return (long)acc; }"
    echo "int main(void) { report(bench_$n($NV)); return 0; }"; } > $K/$n/$n.c
  gcc -m32 -O0 -w $K/$n/$n.c $T/rep.c -o $T/r_$n && $T/r_$n > $K/$n/$n.out
  [ "$(cat $K/x_sf_$op/x_sf_$op.out)" = "$(cat $K/x_crt_$op/x_crt_$op.out)" ] && [ "$(cat $K/x_sf_$op/x_sf_$op.out)" = "$(cat $K/x_sfp_$op/x_sfp_$op.out)" ] || { echo "FAIL: $op checksums differ: kernels are not the same function"; exit 1; }
  echo "$op: ours $(cat $K/x_sf_$op/x_sf_$op.out) crt $(cat $K/x_crt_$op/x_crt_$op.out) softfp $(cat $K/x_sfp_$op/x_sfp_$op.out)"
done
