#!/bin/bash
# usage: tests/x86_kernels64.sh [RT_DIR [OUT_DIR [NV]]] -> kernels x_sf_cmp64 (the six f64 compare entries) from RT_DIR's
# lib/fp/f64 under -DSF_INTABI and config/x86_m32, flattened to one freestanding file, for the vsgcc harness (486-table clocks, llrm/gcc/clang variants).
# RT_DIR defaults to this tree's runtime/compiler-rt, OUT_DIR to the vsgcc kernels directory; NV vectors from gen_vectors64.c.
set -e
GEN=$(dirname "$(readlink -f "$0")")
RT=$(cd "${1:-$(dirname "$0")/..}" && pwd); cd "$RT"; NV=${3:-400}
K=${2:-$(cd "$(dirname "$0")/../../../crates/target/llrm-x86-m32/vsgcc/kernels" && pwd)}; mkdir -p "$K"; K=$(cd "$K" && pwd)
SF_CFG=$(sed -E 's/\buint(32|64)_t\b/sfu\1/g' config/x86_m32/config.h); export SF_CFG; T=$(mktemp -d); trap 'rm -r $T' EXIT
cc -O2 -ffp-contract=off "$GEN/gen_vectors64.c" -o $T/gen && $T/gen $NV > $T/vectors.h
decl='extern void report(long value);
typedef unsigned char sfu8; typedef signed char sfi8; typedef short sfi16; typedef unsigned short sfu16; typedef int sfi32; typedef unsigned int sfu32; typedef unsigned long long sfu64; typedef long long sfi64;
#define UINT32_C(x) x##u
#define UINT64_C(x) x##ull
#define INT32_MAX 2147483647
#define INT32_MIN (-2147483647-1)
#define UINT32_MAX 4294967295u
#define INT64_MAX 9223372036854775807ll
#define UINT64_MAX 18446744073709551615ull'
flat() { for f in include/softfloat.h include/sf_helpers.h "$@"; do
    python3 "$GEN/flatten.py" $f | sed -E '/#include <(stdint|stddef|limits)\.h>/d; /#include "(softfloat|sf_helpers|sf_int)\.h"/d; s/\buint8_t\b/sfu8/g; s/\bint8_t\b/sfi8/g; s/\buint16_t\b/sfu16/g; s/\bint16_t\b/sfi16/g; s/\buint32_t\b/sfu32/g; s/\bint32_t\b/sfi32/g; s/\buint64_t\b/sfu64/g; s/\bint64_t\b/sfi64/g'
  done | awk 'BEGIN{print "#define SF_INTABI 1"; if (ENVIRON["SF_CFG"]) print ENVIRON["SF_CFG"]} {print}'; }
mk() { n=$1; srcs=$2; decls=$3; body=$4; mkdir -p $K/$n
  { echo "/* $n: runtime/compiler-rt f64 under -DSF_INTABI over $NV vectors; generated by tests/x86_kernels64.sh */"
    echo "$decl"; cd "$RT"; flat $srcs; sed 's/uint32_t/sfu32/' $T/vectors.h
    echo "$decls"
    echo "long bench_$n(long n) { long i; sfu32 acc = 0; for (i = 0; i < n; ++i) { const sfu32 *v = V[i % NV]; sfu64 a = ((sfu64)v[0] << 32) | v[1], b = ((sfu64)v[2] << 32) | v[3]; $body } return (long)acc; }"
    echo "int main(void) { report(bench_$n($NV)); return 0; }"
  } > $K/$n/$n.c
  printf '#include <stdio.h>\nvoid report(long v) { printf("%%ld\\n", v); }\n' > $T/rep.c
  gcc -m32 -O0 -w $K/$n/$n.c $T/rep.c -o $T/ref && $T/ref > $K/$n/$n.out; }
mk x_sf_cmp64 "lib/fp/f64/cmp.c" 'int __eqdf2(sfu64, sfu64); int __nedf2(sfu64, sfu64); int __ltdf2(sfu64, sfu64); int __ledf2(sfu64, sfu64); int __gedf2(sfu64, sfu64); int __gtdf2(sfu64, sfu64);' \
  'acc = acc * 31 + (sfu32)__eqdf2(a, b) + 3 * (sfu32)__nedf2(a, b) + 5 * (sfu32)__ltdf2(a, b) + 7 * (sfu32)__ledf2(a, b) + 11 * (sfu32)__gedf2(a, b) + 13 * (sfu32)__gtdf2(a, b);'
echo "wrote $K/x_sf_cmp64"
