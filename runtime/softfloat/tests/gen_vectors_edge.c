/* Like gen_vectors.c, but the operands target the hand-written m68k paths that random bits rarely reach:
 * divide digits whose top halves match (qhat = 0xFFFF), add carries into inf, exact ties, x - x, exponent gaps 24..27,
 * denormal results from mul/div (ties included), overflow at the largest finite value, and int to float ties.
 * cc -O2 -ffp-contract=off tests/gen_vectors_edge.c -o gen && ./gen [n] > vectors.h */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static uint64_t rng = 0x2545F4914F6CDD1Dull;
static uint32_t rnd(void) { rng ^= rng << 13; rng ^= rng >> 7; rng ^= rng << 17; return (uint32_t)(rng >> 16); }
static float b2f(uint32_t b) { float f; memcpy(&f, &b, 4); return f; }
static uint32_t f2b(float f) { uint32_t b; memcpy(&b, &f, 4); return b; }
static uint32_t mk(uint32_t s, uint32_t e, uint32_t m) { return s << 31 | (e & 255) << 23 | (m & 0x7FFFFF); }

/* The 68000 divide's two 16-bit quotient digits: does digit k (1 or 2) start with equal top halves? */
static int div_digit_overflow(uint32_t ma, uint32_t mb, int k)
{
    uint32_t u = ma << 8, v = mb << 8;
    if (u >= v) u >>= 1;
    if (u >> 16 == v >> 16) return k == 1;
    uint64_t r = ((uint64_t)u << 16) % v;
    return k == 2 && (r >> 16) == (v >> 16);
}

static void pair(uint32_t *a, uint32_t *b)
{
    uint32_t s1 = rnd() & 1, s2 = rnd() & 1, e = 1 + rnd() % 253, m = rnd(), m2 = rnd();
    switch (rnd() % 11) {
    case 0: /* divide digit 1 or 2 with equal top halves */
        for (int k = 1 + (rnd() & 1);;) {
            uint32_t ma = 0x800000 | (rnd() & 0x7FFFFF), mb = 0x800000 | (rnd() & 0x7FFFFF);
            if (k == 1) mb = (ma & ~0xFFu) | (rnd() & 0xFF);
            if (div_digit_overflow(ma, mb, k)) { *a = mk(s1, e, ma), *b = mk(s2, 1 + rnd() % 253, mb); return; }
        }
    case 1: /* same-sign add near the top: carries into inf */
        *a = mk(s1, 252 + rnd() % 3, m), *b = mk(s1, 250 + rnd() % 5, m2); return;
    case 2: /* add ties: b is half an ulp of a times an odd or even pattern */
        *a = mk(s1, e, m), *b = mk(s2, e > 24 ? e - 24 : 0, (rnd() & 1) ? 0 : m2 & 1); return;
    case 3: /* x - x, x + -x, zeros */
        *a = mk(s1, rnd() & 1 ? 0 : e, m), *b = *a ^ ((rnd() & 1) << 31); if (rnd() % 4 == 0) *a &= 0x80000000u, *b &= 0x80000000u; return;
    case 4: /* exponent gaps 23..28 with patterns at the edge of the far-gap return */
        *a = mk(s1, e + 28, rnd() & 1 ? 0 : m), *b = mk(s2, e + 28 - 23 - rnd() % 6, rnd() % 3 == 0 ? 0x7FFFFF : rnd() % 2 ? 0x400000 : m2); return;
    case 5: /* mul/div results in or near the denormal range */
        *a = mk(s1, rnd() % 40, m), *b = mk(s2, 100 + rnd() % 40, rnd() & 1 ? 0 : m2); return;
    case 6: /* mul/div near the overflow edge */
        *a = mk(s1, 254 - rnd() % 3, rnd() & 1 ? 0x7FFFFF : m), *b = mk(s2, 126 + rnd() % 3, rnd() & 1 ? 0 : m2); return;
    case 7: /* tiny denormals against everything */
        *a = mk(s1, 0, 1u << (rnd() % 23) | (rnd() & 1)), *b = mk(s2, rnd() & 255, m2); if (rnd() & 1) { uint32_t t = *a; *a = *b; *b = t; } return;
    case 8: /* cancellation: equal or adjacent exponents, close mantissas */
        *a = mk(s1, e, m), *b = mk(s2, e - (rnd() & 1), m + (rnd() % 7) - 3); return;
    case 9: /* int to float ties and their neighbours: 25 significant bits shifted up to the top */
        { uint32_t t = (0x1000000 | (rnd() & 0xFFFFFF)) | 1; int sh = rnd() % 8; *a = (t << sh) + (rnd() % 3 == 0 ? (rnd() & 1 ? 1u : -1u) : 0); *b = mk(s2, e, m2); return; }
    default: /* inf, NaN, zero against anything */
        { static const uint32_t sp[] = {0x7F800000, 0xFF800000, 0x7FC00000, 0x7F800001, 0xFFFFFFFF, 0, 0x80000000, 1};
          *a = sp[rnd() % 8], *b = rnd() % 3 ? sp[rnd() % 8] : mk(s2, e, m2); if (rnd() & 1) { uint32_t t = *a; *a = *b; *b = t; } }
    }
}

int main(int argc, char **argv)
{
    int n = argc > 1 ? atoi(argv[1]) : 3000;
    printf("/* generated by tests/gen_vectors_edge.c */\n#define NV %d\n", n);
    printf("static const uint32_t V[NV][11] = { /* a, b, add, sub, mul, div, cmp, i2f(a), u2f(a), f2i(a), f2u(a) */\n");
    for (int i = 0; i < n; i++) {
        uint32_t a, b;
        pair(&a, &b);
        volatile float x = b2f(a), y = b2f(b);
        int cmp = x < y ? -1 : x > y ? 1 : x == y ? 0 : 2;
        volatile float fi = (float)(int32_t)a, fu = (float)a;
        int ok_i = x > -2147483648.0f && x < 2147483648.0f, ok_u = x > -1.0f && x < 4294967296.0f;
        uint32_t i2i = ok_i ? (uint32_t)(int32_t)x : 0, f2u = ok_u ? (uint32_t)x : 0;
        printf("  {0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu,%d,0x%08Xu,0x%08Xu,0x%08Xu,0x%08Xu},\n", a, b, f2b(x + y), f2b(x - y),
               f2b(x * y), f2b(x / y), cmp, f2b(fi), f2b(fu), ok_i ? i2i : 0xDEADBEEFu, ok_u ? f2u : 0xDEADBEEFu);
    }
    printf("};\n");
    return 0;
}
