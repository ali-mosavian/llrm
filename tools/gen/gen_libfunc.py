#!/usr/bin/env python3
"""Generate crates/ir/llrm-mir/src/libfunc/table.rs from the pin's TargetLibraryInfo.td.

    tools/gen/gen_libfunc.py [--check]      write the table, or fail if the checked-in one differs

The pin is LLVM_SRC (default ~/scratch/llvm-src) at the commit PIN. With --check and no source tree it passes.
"""
import os
import re
import subprocess
import sys
from pathlib import Path

PIN = "d1106deb71cc81016406a1917d0508d2df296266"
ROOT = Path(__file__).resolve().parent.parent.parent
OUT = ROOT / "crates/ir/llrm-mir/src/libfunc/table.rs"
SRC = Path(os.environ.get("LLVM_SRC", Path.home() / "scratch/llvm-src")) / "llvm/include/llvm/Analysis/TargetLibraryInfo.td"
TYPES = ["Void", "Bool", "Int16", "Int32", "Int", "IntPlus", "Long", "IntX", "Int64", "LLong", "SizeT", "SSizeT", "Flt", "Dbl", "LDbl", "Floating", "Ptr", "Struct", "Ellip", "Same"]
DEF = re.compile(r'def\s+(\w+)\s*:\s*TargetLibCall<\s*"((?:[^"\\]|\\.)*)"\s*,\s*(\?|\w+)\s*(?:,\s*\[([^\]]*)\])?\s*>\s*;', re.S)


def camel(name: str) -> str:
    out = "".join(part[:1].upper() + part[1:] for part in name.split("_") if part)
    return out if not out[0].isdigit() else "F" + out


def render() -> str:
    defs = DEF.findall(re.sub(r"/\*.*?\*/", "", re.sub(r"//[^\n]*", "", SRC.read_text()), flags=re.S))
    assert len(defs) == 528, len(defs)
    variants = []
    for name, string, *_ in defs:
        # `exit` and `_Exit` are both `Exit`: the later takes its symbol, `_` spelled `Under`.
        variant = camel(name)
        if variant in variants:
            variant = camel(re.sub(r"^_+", lambda m: "under_" * len(m.group()), string))
        variants.append(variant)
    assert len(set(variants)) == len(variants), [v for v in variants if variants.count(v) > 1]
    assert len({string for _, string, *_ in defs}) == len(defs), "two defs share a name"
    lines = [
        f"// @generated by tools/gen/gen_libfunc.py from TargetLibraryInfo.td at {PIN}; do not edit.",
        "",
        "use super::FuncArgType::{self, *};",
        "",
        "/// `LibFunc`: the library functions LLVM recognizes, in the order of `TargetLibraryInfo.td`.",
        "#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq, PartialOrd, Ord)]",
        "#[repr(u16)]",
        "pub enum LibFunc {",
    ]
    lines += [f"    {v}," for v in variants]
    lines += ["}", "", f"pub const NUM_LIB_FUNCS: usize = {len(defs)};", "", "pub const ALL: [LibFunc; NUM_LIB_FUNCS] = ["]
    lines += [f"    LibFunc::{v}," for v in variants]
    lines += ["];", "", "/// The standard name of each, by `LibFunc as usize`.", "pub const NAMES: [&str; NUM_LIB_FUNCS] = ["]
    lines += [f'    "{string}",' for _, string, *_ in defs]
    lines += ["];", "", "/// The prototype of each: the return type, then the arguments.", "pub const SIGNATURES: [&[FuncArgType]; NUM_LIB_FUNCS] = ["]
    for _, _, ret, args in defs:
        # `?` is a prototype the pin checks by hand (cabs, sincospi_stret, size_returning_new): none here.
        types = [] if ret == "?" else [ret] + [a.strip() for a in args.split(",") if a.strip()]
        assert all(t in TYPES for t in types), types
        lines.append(f"    &[{', '.join(types)}],")
    lines.append("];")
    return "\n".join(lines) + "\n"


def formatted(text: str, out: Path) -> str:
    """`text` as tools/fmt.sh lays out `out`: the checked-in file is formatted, so the generator's raw output is never what --check finds."""
    done = subprocess.run([str(ROOT / "tools/fmt.sh"), "--stdin", str(out)], input=text, capture_output=True, text=True)
    if done.returncode != 0:
        raise SystemExit(f"tools/fmt.sh --stdin {out.name}: {done.stderr.strip()}")
    return done.stdout


def main() -> int:
    if not SRC.is_file():
        print(f"gen_libfunc: no {SRC}: skipped", file=sys.stderr)
        return 0 if "--check" in sys.argv else 1
    text = formatted(render(), OUT)
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            print("gen_libfunc: crates/ir/llrm-mir/src/libfunc/table.rs is stale: run tools/gen/gen_libfunc.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
