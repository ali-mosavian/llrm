#!/usr/bin/env python3
"""gen_qbvga.py DOSBOX_X_SRC > runtime/qb/dev/host/vgadata.c: the BIOS's three text fonts (8, 14 and 16 rows, 256
characters) and the EGA's 64 colours (rgbRGB order, as the AC palette registers name them) and the VGA's default 256 (6 bits a channel) as DOSBox-X holds them, so a host screen
draws the glyphs and colours the DOS goldens show."""
import re
import sys
from pathlib import Path

source = (Path(sys.argv[1]) / "src/ints/int10_memory.cpp").read_text()
modes = (Path(sys.argv[1]) / "src/ints/int10_modes.cpp").read_text()
print("/* The BIOS's text fonts (256 characters of 8, 14 and 16 rows, one byte a row, the leftmost pixel the high bit) and the\n   VGA palettes (6 bits a channel). Generated by tools/gen_qbvga.py from the tables of DOSBox-X's src/ints: bitmaps of\n   the IBM VGA typeface and its colours, which the DOS runtime reads from the BIOS through INT 10h. */")
print('#include "vgadata.h"\n')
for rows in (8, 14, 16):
    body = re.search(rf"int10_font_{rows:02d}\[256 \* {rows}\]\s*=\s*\{{(.*?)\}};", source, re.S).group(1)
    values = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body)]
    assert len(values) == 256 * rows, (rows, len(values))
    print(f"const unsigned char qb_vga_font_{rows}[256 * {rows}] = {{")
    for at in range(0, len(values), 16):
        print("    " + ", ".join(f"0x{v:02X}" for v in values[at : at + 16]) + ",")
    print("};\n")
for name, count, out in (("text_palette", 64, "ega_palette"), ("vga_palette", 248, "vga_palette")):
    body = re.search(rf"{name}\[{count}\]\[3\]\s*=\s*\{{(.*?)\n\}};", modes, re.S).group(1)
    values = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", body)]
    assert len(values) == count * 3, (name, len(values))
    values += [0] * (256 * 3 - len(values)) if name == "vga_palette" else []
    print(f"const unsigned char qb_{out}[{len(values) // 3}][3] = {{")
    for at in range(0, len(values), 3):
        print("    {" + ", ".join(f"0x{v:02X}" for v in values[at : at + 3]) + "},")
    print("};\n")
