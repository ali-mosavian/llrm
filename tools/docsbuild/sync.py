"""Pre-generate what GitHub shows without a build: the pass reference and the figure images.

`plan(root)` computes every file `--sync` writes or deletes; `apply` writes them. The
sources of truth are the `//!` headers of the crates and the ```fig fences in the
documents. Everything here is a pure function of those, in sorted order.
"""
from __future__ import annotations

import posixpath
import re
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import passdocs  # noqa: E402
from docsbuild import figblock, figures  # noqa: E402

REFERENCE = "docs/optimizations/reference"
FIGURES = "docs/assets/figures"
COMMAND = "python3 tools/docsbuild/build.py --sync"


@dataclass
class Plan:
    writes: dict[str, str] = field(default_factory=dict)  # changed or new text files, by repository path
    deletes: list[str] = field(default_factory=list)
    errors: list[str] = field(default_factory=list)

    @property
    def drift(self) -> list[str]:
        return sorted([*self.writes, *self.deletes])


def reference_pages(root: Path) -> dict[str, str]:
    """The pass, analysis and backend pages, each under a banner naming where it comes from."""
    with tempfile.TemporaryDirectory() as tmp:
        passdocs.write(Path(tmp), root, "main")
        pages = {f.name: f.read_text(encoding="utf-8") for f in sorted(Path(tmp).glob("*.md"))}
    dirs = {name: directory for name, _title, directory, _kind in passdocs.PAGES}
    out = {}
    for name, text in pages.items():
        where = ", ".join(f"`{d}`" for d in ([dirs[name[:-3]]] if name[:-3] in dirs else dirs.values()))
        banner = f"> Generated by `tools/docsbuild/build.py --sync` from the `//!` headers of {where}; edit the headers, not this file.\n\n"
        out[f"{REFERENCE}/{name}"] = banner + text
    return out


def slug_base(path: str) -> str:
    return path[:-3].replace("/", "-")


def alt(fig: figures.Figure) -> str:
    return re.sub(r"\s+", " ", (fig.title or fig.desc.split(":")[0]).replace("[", "(").replace("]", ")")).strip()


def block(slug: str, alt_text: str, image: str, spec: str) -> list[str]:
    return [
        f"<!-- figure:{slug} -->",
        f"![{alt_text}]({image})",
        "",
        "<details><summary>Figure source</summary>",
        "",
        "```fig",
        *spec.split("\n"),
        "```",
        "",
        "</details>",
        "<!-- /figure -->",
    ]


def rewrite(path: str, text: str) -> tuple[str, dict[str, str], list[str]]:
    """`text` with every figure as a committed block, the SVGs it refers to by path, and problems."""
    found, errs = figblock.find(text)
    problems = [f"{path}:{line}: {msg}" for line, msg in errs]
    lines = text.split("\n")
    svgs: dict[str, str] = {}
    for n, f in reversed(list(enumerate(found, 1))):
        slug = f"{slug_base(path)}-{n}"
        try:
            fig = figures.build(f.spec)
        except figures.FigureError as e:
            problems.append(f"{path}:{f.spec_line + e.line - 1}: figure: {e.message}")
            continue
        file = f"{FIGURES}/{slug}.svg"
        svgs[file] = fig.svg + "\n"
        image = posixpath.relpath(file, posixpath.dirname(path) or ".")
        lines[f.start : f.end] = block(slug, alt(fig), image, f.spec)
    return "\n".join(lines), svgs, problems


def markdown_files(root: Path, generated: dict[str, str]) -> list[str]:
    on_disk = [p.relative_to(root).as_posix() for p in (root / "docs").rglob("*.md")]
    return sorted({*(p for p in ("readme.md", "agents.md") if (root / p).is_file()), *on_disk, *generated})


def plan(root: Path) -> Plan:
    out = Plan()
    generated = reference_pages(root)
    svgs: dict[str, str] = {}
    for path in markdown_files(root, generated):
        old = (root / path).read_text(encoding="utf-8") if (root / path).is_file() else None
        text, files, problems = rewrite(path, generated.get(path, old))
        out.errors += problems
        svgs.update(files)
        if text != old:
            out.writes[path] = text
    for file, text in sorted(svgs.items()):
        if not (root / file).is_file() or (root / file).read_text(encoding="utf-8") != text:
            out.writes[file] = text
    folder = root / FIGURES
    out.deletes = sorted(
        p.relative_to(root).as_posix() for p in folder.glob("*.svg") if p.relative_to(root).as_posix() not in svgs
    ) if folder.is_dir() else []
    return out


def apply(root: Path, p: Plan) -> None:
    for path, text in p.writes.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(text, encoding="utf-8")
    for path in p.deletes:
        (root / path).unlink()


def drift_message(p: Plan) -> str:
    files = "\n".join(f"  {f}" for f in p.drift)
    return f"generated docs are out of date; run {COMMAND}\n{files}"
