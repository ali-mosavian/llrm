"""--sync: figure sources, images, the committed pass pages, and the check that they are current."""
import passdocs
from docsbuild import build, figblock, sync

HEADER = """//! Walks the thing.
//!
//! # How it works
//!
//! Text.
//!
//! ```fig
//! kind: graph
//! node A "a"
//! ```
//!
//! # Provides
//!
//! Facts.
"""
SPEC = 'kind: lanes\ntitle: A timeline\nlane a "a"'
FENCE = f"```fig\n{SPEC}\n```\n"
FIGS = "docs/assets/figures"


def repo(tmp_path, files):
    root = tmp_path / "repo"
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text, encoding="utf-8")
    return root


def synced(root):
    p = sync.plan(root)
    assert not p.errors, p.errors
    sync.apply(root, p)
    return p


BASE = {
    "readme.md": "# Home\n\n[d](docs/readme.md)\n",
    "docs/readme.md": "# Docs\n\n[x](a/b/c.md)\n",
    "docs/a/b/c.md": "# C\n\ntext\n\n" + FENCE + "\nafter\n",
    "crates/opt/llrm-analysis/src/walk.rs": HEADER,
}
IMG = "![A timeline](../../assets/figures/docs-a-b-c-1.svg)"


def test_reference_pages_are_written_under_a_banner(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    ref = root / "docs/optimizations/reference"
    assert sorted(f.name for f in ref.glob("*.md")) == ["analyses.md", "backend.md", "index.md", "passes.md"]
    assert (ref / "analyses.md").read_text().split("\n")[0] == (
        "> Generated by `tools/docsbuild/build.py --sync` from the `//!` headers of "
        "`crates/opt/llrm-analysis/src`; edit the headers, not this file."
    )
    index = (ref / "index.md").read_text().split("\n")[0]
    assert all(d in index for d in ("llrm-transforms/src", "llrm-analysis/src", "backend/llrm-core/src/backend"))


def test_bare_fence_moves_to_a_fig_and_leaves_the_image(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    assert (root / "docs/a/b/c.md").read_text() == f"# C\n\ntext\n\n{IMG}\n\nafter\n"
    assert (root / f"{FIGS}/docs-a-b-c-1.fig").read_text() == SPEC + "\n"
    assert (root / f"{FIGS}/docs-a-b-c-1.svg").read_text().startswith("<svg")


def test_old_figure_block_moves_to_a_fig_too(tmp_path):
    old = f"# C\n\n<!-- figure:x -->\n![t](b.svg)\n\n<details><summary>Figure source</summary>\n\n{FENCE}\n</details>\n<!-- /figure -->\n"
    root = repo(tmp_path, dict(BASE, **{"docs/a/b/c.md": old}))
    synced(root)
    assert (root / "docs/a/b/c.md").read_text() == f"# C\n\n{IMG}\n"
    assert (root / f"{FIGS}/docs-a-b-c-1.fig").read_text() == SPEC + "\n"


def test_image_path_is_relative_to_the_document(tmp_path):
    root = repo(tmp_path, dict(BASE, **{"readme.md": "# Home\n\n" + FENCE}))
    synced(root)
    assert "![A timeline](docs/assets/figures/readme-1.svg)" in (root / "readme.md").read_text()


def test_a_new_fence_takes_the_next_free_slug(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    doc = root / "docs/a/b/c.md"
    doc.write_text(doc.read_text() + "\n" + FENCE.replace("A timeline", "Second"))
    synced(root)
    assert "docs-a-b-c-2.svg" in doc.read_text() and (root / f"{FIGS}/docs-a-b-c-2.fig").is_file()
    assert "A timeline" in (root / f"{FIGS}/docs-a-b-c-1.fig").read_text()


def test_header_figure_becomes_an_image_on_the_generated_page_without_a_fig(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    page = (root / "docs/optimizations/reference/analyses.md").read_text()
    assert "![Graph, 1 nodes](../../assets/figures/llrm-analysis-walk-1.svg)" in page
    assert "```fig" not in page
    assert (root / f"{FIGS}/llrm-analysis-walk-1.svg").is_file()
    assert not (root / f"{FIGS}/llrm-analysis-walk-1.fig").exists()


def test_sync_twice_changes_nothing(tmp_path):
    root = repo(tmp_path, BASE)
    assert synced(root).writes
    again = sync.plan(root)
    assert again.writes == {} and again.deletes == [] and again.errors == []


def test_edited_fig_redraws_its_svg(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    fig = root / f"{FIGS}/docs-a-b-c-1.fig"
    fig.write_text(SPEC + '\nlane b "bee"\n')
    p = synced(root)
    assert f"{FIGS}/docs-a-b-c-1.svg" in p.writes
    assert ">bee<" in (root / f"{FIGS}/docs-a-b-c-1.svg").read_text()


def test_svg_with_no_source_is_deleted(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    stale = root / f"{FIGS}/gone-1.svg"
    stale.write_text("<svg/>")
    assert synced(root).deletes == [f"{FIGS}/gone-1.svg"] and not stale.exists()


def test_fig_no_document_uses_is_flagged(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    (root / f"{FIGS}/orphan.fig").write_text(SPEC + "\n")
    assert sync.plan(root).errors == [f"{FIGS}/orphan.fig: not referenced by any document"]


def test_image_without_a_source_is_flagged(tmp_path):
    root = repo(tmp_path, dict(BASE, **{"docs/a/b/c.md": "# C\n\n![x](../../assets/figures/nope.svg)\n"}))
    assert sync.plan(root).errors == [f"docs/a/b/c.md: {FIGS}/nope.svg has no nope.fig"]


def test_fig_error_names_the_fig_line_and_writes_nothing(tmp_path, monkeypatch):
    bad = 'kind: graph\nnode A "a"\nedge A -> Z\n'
    root = repo(tmp_path, dict(BASE, **{"docs/a/b/c.md": f"# C\n\n![x](../../assets/figures/z.svg)\n", f"{FIGS}/z.fig": bad}))
    assert sync.plan(root).errors == [f"{FIGS}/z.fig:3: figure: unknown node 'Z'"]
    monkeypatch.setattr(build, "ROOT", root)
    assert build.main(["--sync"]) == 1
    assert not (root / "docs/optimizations").exists()


def test_fence_in_a_document_error_line_counts_from_the_document(tmp_path):
    doc = "# C\n\n```fig\nkind: graph\nnode A \"a\"\nedge A -> Z\n```\n"
    root = repo(tmp_path, dict(BASE, **{"docs/a/b/c.md": doc}))
    assert sync.plan(root).errors == ["docs/a/b/c.md:6: figure: unknown node 'Z'"]


def test_check_fails_on_drift_and_names_the_command(tmp_path, monkeypatch, capsys):
    root = repo(tmp_path, BASE)
    monkeypatch.setattr(build, "ROOT", root)
    assert build.main(["--check"]) == 1
    out = capsys.readouterr().out
    assert "run python3 tools/docsbuild/build.py --sync" in out and "docs/a/b/c.md" in out
    assert build.main(["--sync"]) == 0
    assert build.main(["--check"]) == 0


def test_check_flags_a_fence_left_in_a_committed_document(tmp_path):
    root = repo(tmp_path, BASE)
    assert sync.fence_errors(root) == [f"docs/a/b/c.md:5: figure fence in a document; run {sync.COMMAND}"]
    synced(root)
    assert sync.fence_errors(root) == []


def test_fence_shown_inside_a_text_block_is_not_a_figure(tmp_path):
    doc = "# C\n\n```text\n```fig\nkind: graph\n```\n```\n"
    assert figblock.find(doc.replace("```text\n```fig", "```text\n~~~fig"))[0] == []


def test_repository_is_in_sync():
    p = sync.plan(build.ROOT)
    assert p.errors == [] and p.drift == [] and sync.fence_errors(build.ROOT) == [], sync.drift_message(p)


def test_image_syntax_in_code_is_not_a_reference(tmp_path):
    """A doc showing `![x](a/assets/figures/n.svg)` in code was flagged as an image with no source."""
    doc = "# C\n\nWrite `![x](../assets/figures/n.svg)`.\n\n```text\n![x](../assets/figures/m.svg)\n```\n"
    root = repo(tmp_path, dict(BASE, **{"docs/a/b/c.md": doc}))
    assert sync.plan(root).errors == []


# Directories whose every file has the header; add transforms and the backend phases as theirs are written.
HEADERS_REQUIRED = ["crates/opt/llrm-analysis/src"]


def test_every_file_of_a_required_directory_has_a_header():
    """A pass without its `//!` summary, `# How it works` and `# Runs`/`# Provides` is missing from the reference."""
    assert passdocs.check(HEADERS_REQUIRED, build.ROOT) == []
