"""--sync: committed pass pages and figure images, and the check that they are current."""
import re
from pathlib import Path

from docsbuild import build, sync

HEADER = """//! Walks the thing.
//!
//! # How it works
//!
//! Text.
//!
//! ```fig
//! kind: graph
//! node A "a"
//! ```
//!
//! # Provides
//!
//! Facts.
"""
FENCE = '```fig\nkind: lanes\ntitle: A timeline\nlane a "a"\n```\n'


def repo(tmp_path, files):
    root = tmp_path / "repo"
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text, encoding="utf-8")
    return root


def synced(root):
    p = sync.plan(root)
    assert not p.errors
    sync.apply(root, p)
    return p


BASE = {
    "readme.md": "# Home\n\n[d](docs/readme.md)\n",
    "docs/readme.md": "# Docs\n\n[x](a/b/c.md)\n",
    "docs/a/b/c.md": "# C\n\ntext\n\n" + FENCE + "\nafter\n",
    "crates/opt/llrm-analysis/src/walk.rs": HEADER,
}


def test_reference_pages_are_written_under_a_banner(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    ref = root / "docs/optimizations/reference"
    assert sorted(f.name for f in ref.glob("*.md")) == ["analyses.md", "backend.md", "index.md", "passes.md"]
    first = (ref / "analyses.md").read_text().split("\n")[0]
    assert first == (
        "> Generated by `tools/docsbuild/build.py --sync` from the `//!` headers of "
        "`crates/opt/llrm-analysis/src`; edit the headers, not this file."
    )
    index = (ref / "index.md").read_text().split("\n")[0]
    assert all(d in index for d in ("llrm-transforms/src", "llrm-analysis/src", "backend/llrm-core/src/backend"))


def test_bare_fence_becomes_a_block_with_the_source_collapsed(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    text = (root / "docs/a/b/c.md").read_text()
    assert text == (
        "# C\n\ntext\n\n<!-- figure:docs-a-b-c-1 -->\n"
        "![A timeline](../../assets/figures/docs-a-b-c-1.svg)\n\n"
        "<details><summary>Figure source</summary>\n\n" + FENCE + "\n</details>\n<!-- /figure -->\n\nafter\n"
    )
    assert (root / "docs/assets/figures/docs-a-b-c-1.svg").read_text().startswith("<svg")


def test_image_path_is_relative_to_the_document(tmp_path):
    root = repo(tmp_path, dict(BASE, **{"readme.md": "# Home\n\n" + FENCE}))
    synced(root)
    assert "![A timeline](docs/assets/figures/readme-1.svg)" in (root / "readme.md").read_text()


def test_header_figure_lands_on_the_generated_page(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    page = (root / "docs/optimizations/reference/analyses.md").read_text()
    m = re.search(r"<!-- figure:(\S+) -->\n!\[Graph, 1 nodes\]\((\S+)\)", page)
    assert m and m.group(1) == "docs-optimizations-reference-analyses-1"
    assert (root / "docs/optimizations/reference" / m.group(2)).resolve().is_file()


def test_sync_twice_changes_nothing(tmp_path):
    root = repo(tmp_path, BASE)
    first = synced(root)
    assert first.writes
    again = sync.plan(root)
    assert again.writes == {} and again.deletes == [] and again.drift == []


def test_edited_spec_in_a_block_redraws_the_image(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    doc = root / "docs/a/b/c.md"
    doc.write_text(doc.read_text().replace('lane a "a"', 'lane a "a"\nlane b "b"').replace("A timeline", "T2"))
    p = synced(root)
    assert "docs/assets/figures/docs-a-b-c-1.svg" in p.writes
    assert "![T2](" in doc.read_text() and ">b<" in (root / "docs/assets/figures/docs-a-b-c-1.svg").read_text()


def test_image_no_block_refers_to_is_deleted(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    stale = root / "docs/assets/figures/gone-1.svg"
    stale.write_text("<svg/>")
    p = synced(root)
    assert p.deletes == ["docs/assets/figures/gone-1.svg"] and not stale.exists()


def test_figure_error_names_the_document_line_and_writes_nothing(tmp_path):
    bad = "# C\n\n<!-- figure:x -->\n![a](b.svg)\n\n<details>\n\n```fig\nkind: graph\nnode A \"a\"\nedge A -> Z\n```\n\n</details>\n<!-- /figure -->\n"
    root = repo(tmp_path, dict(BASE, **{"docs/a/b/c.md": bad}))
    p = sync.plan(root)
    assert p.errors == ["docs/a/b/c.md:11: figure: unknown node 'Z'"]
    main = build.main
    build.ROOT, old = root, build.ROOT
    try:
        assert main(["--sync"]) == 1
    finally:
        build.ROOT = old
    assert not (root / "docs/optimizations").exists()


def test_check_fails_on_drift_and_names_the_command(tmp_path, monkeypatch, capsys):
    root = repo(tmp_path, BASE)
    monkeypatch.setattr(build, "ROOT", root)
    assert build.main(["--check"]) == 1
    out = capsys.readouterr().out
    assert "run python3 tools/docsbuild/build.py --sync" in out and "docs/a/b/c.md" in out
    assert build.main(["--sync"]) == 0
    assert build.main(["--check"]) == 0


def test_site_draws_the_figure_inline_from_its_block(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    assert build.build(root, tmp_path / "site") == []
    page = (tmp_path / "site/a/b/c.html").read_text()
    assert "<svg" in page and "Figure source" not in page and "figure:" not in page and "<img" not in page


def test_site_reports_a_block_figure_error_at_its_spec_line(tmp_path):
    bad = "# C\n\n<!-- figure:x -->\n![a](b.svg)\n\n<details>\n\n```fig\nkind: graph\nnode A \"a\"\nedge A -> Z\n```\n\n</details>\n<!-- /figure -->\n"
    root = repo(tmp_path, dict(BASE, **{"docs/a/b/c.md": bad}))
    errors = build.build(root, tmp_path / "site")
    assert "docs/a/b/c.md:11: figure: unknown node 'Z'" in errors


def test_repository_is_in_sync():
    p = sync.plan(build.ROOT)
    assert p.errors == [] and p.drift == [], sync.drift_message(p)
