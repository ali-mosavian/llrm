"""--sync: figure sources, images, the committed pass pages, and the check that they are current."""
import passdocs
from docsbuild import build, figblock, sync

HEADER = """//! Walks the thing.
//!
//! # How it works
//!
//! Text.
//!
//! ```fig
//! kind: graph
//! node A "a"
//! ```
//!
//! # Provides
//!
//! Facts.
"""
SPEC = 'kind: lanes\ntitle: A timeline\nlane a "a"'
FENCE = f"```fig\n{SPEC}\n```\n"
FIGS = "docs/assets/figures"


def repo(tmp_path, files):
    root = tmp_path / "repo"
    for name, text in files.items():
        (root / name).parent.mkdir(parents=True, exist_ok=True)
        (root / name).write_text(text, encoding="utf-8")
    return root


def synced(root):
    p = sync.plan(root)
    assert not p.errors, p.errors
    sync.apply(root, p)
    return p


BASE = {
    "readme.md": "# Home\n\n[d](docs/readme.md)\n",
    "docs/readme.md": "# Docs\n\n[x](a/b/c.md)\n",
    "docs/a/b/c.md": "# C\n\ntext\n\n" + FENCE + "\nafter\n",
    "crates/opt/llrm-analysis/src/walk.rs": HEADER,
}
IMG = "![A timeline](../../assets/figures/docs-a-b-c-1.png)"


def test_reference_pages_are_written_under_a_banner(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    ref = root / "docs/optimizations/reference"
    assert sorted(f.name for f in ref.glob("*.md")) == ["analyses.md", "backend.md", "index.md", "passes.md"]
    assert (ref / "analyses.md").read_text().split("\n")[0] == (
        "> Generated by `tools/docsbuild/build.py --sync` from the `//!` headers of "
        "`crates/opt/llrm-analysis/src`; edit the headers, not this file."
    )
    index = (ref / "index.md").read_text().split("\n")[0]
    assert all(d in index for d in ("llrm-transforms/src", "llrm-analysis/src", "backend/llrm-core/src/backend"))


def test_bare_fence_moves_to_a_fig_and_leaves_the_image(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
    assert (root / "docs/a/b/c.md").read_text() == f"# C\n\ntext\n\n{IMG}\n\nafter\n"
    assert (root / f"{FIGS}/docs-a-b-c-1.fig").read_text() == SPEC + "\n"
    assert (root / f"{FIGS}/docs-a-b-c-1.png").read_bytes().startswith(b"\x89PNG\r\n\x1a\n")


def test_old_figure_block_moves_to_a_fig_too(tmp_path):
    old = f"# C\n\n<!-- figure:x -->\n![t](b.svg)\n\n<details><summary>Figure source</summary>\n\n{FENCE}\n</details>\n<!-- /figure -->\n"
    root = repo(tmp_path, dict(BASE, **{"docs/a/b/c.md": old}))
    synced(root)
    assert (root / "docs/a/b/c.md").read_text() == f"# C\n\n{IMG}\n"
    assert (root / f"{FIGS}/docs-a-b-c-1.fig").read_text() == SPEC + "\n"


def test_image_path_is_relative_to_the_document(tmp_path):
    root = repo(tmp_path, dict(BASE, **{"readme.md": "# Home\n\n" + FENCE}))
    synced(root)
    assert "![A timeline](docs/assets/figures/readme-1.png)" in (root / "readme.md").read_text()


def test_a_new_fence_takes_the_next_free_slug(tmp_path):
    root = repo(tmp_path, BASE)
    synced(root)
