#!/usr/bin/env python3
"""Reads the pin's `llvm-tblgen --dump-json` into the binary encodings of a target's instructions.

    enctable.py TARGET.json OUT.rs NAMESPACE

One row per instruction of the namespace that has an `Inst` dag (`ascend`, `descend`, `operand`,
`slice`, `encoder`): its width in bits and its pieces, each placed at an absolute bit position of the
encoded integer (bit 0 is the first word's low bit). An operand names the machine operand it reads by
number, as asmtable.py numbers them (a sub-operand `$a.b` is `b`'s place in the `MIOperandInfo`).
"""
import json
import re
import sys

src, out, ns = sys.argv[1:4]
data = json.load(open(src))
ENCODERS = {
    "encodeRelocImm": "RelocImm",
    "encodePCRelImm": "PcRelImm",
    "encodeFPSYSSelect": "FpSysSelect",
    "encodeInverseMoveMask": "InverseMoveMask",
    "encodeScale": "Scale",
    "encodeIndexSuppress": "IndexSuppress",
}


def encoder(args):
    for arg in args:
        node = arg[0]
        if isinstance(node, dict) and node["operator"]["def"] == "encoder":
            m = re.fullmatch(r"(\w+)(?:<(\d+)>)?", node["args"][0][0])
            kind = ENCODERS[m.group(1)]
            return f"Enc::{kind}({m.group(2)})" if m.group(2) else f"Enc::{kind}"
    return "Enc::Plain"


def piece(node, names, lo, name):
    """(width, pieces) of `node` placed at bit `lo`."""
    if isinstance(node, int):
        return 1, [("Const", lo, 1, node)]
    if isinstance(node, list):
        return len(node), [("Const", lo, len(node), sum(int(bit) << at for at, bit in enumerate(node)))]
    op = node["operator"]["def"]
    args = node["args"]
    if op in ("ascend", "descend"):
        parts = [piece(arg[0], names, 0, name) for arg in args]
        width = sum(w for w, _ in parts)
        out, at = [], 0
        for w, pieces in (parts if op == "ascend" else list(reversed(parts))):
            out += [(kind, base + lo + at, *rest) for kind, base, *rest in pieces]
            at += w
        return width, out
    if op == "operand":
        ref, width = args[0][0], args[1][0]
        return width, [("Operand", lo, width, names[ref], 0, encoder(args[2:]))]
    if op == "slice":
        ref, first, last = args[0][0], args[1][0], args[2][0]
        width = abs(last - first) + 1
        return width, [("Operand", lo, width, names[ref], min(first, last), encoder(args[3:]))]
    raise SystemExit(f"{name}: operator {op}")


rows = []
for name, inst in sorted(data.items()):
    if not (isinstance(inst, dict) and inst.get("Namespace") == ns and "Inst" in inst):
        continue
    if "Instruction" not in inst.get("!superclasses", []) or not isinstance(inst["Inst"], dict):
        continue
    at, names = 0, {}
    for arg in inst["OutOperandList"]["args"] + inst["InOperandList"]["args"]:
        parts = data[arg[0]["def"]].get("MIOperandInfo")
        subs = [one[1] for one in parts["args"]] if isinstance(parts, dict) else []
        if arg[1] is not None:
            names[f"${arg[1]}"] = at
            for place, sub in enumerate(subs):
                names[f"${arg[1]}.{sub}"] = at + place
        at += max(1, len(subs))
    width, pieces = piece(inst["Inst"], names, 0, name)
    rows.append((name, width, pieces))

with open(out, "w") as f:
    f.write("//! The binary encodings of the pin's instructions.\n//!\n")
    f.write("//! Generated by `tools/dagisel/regen-target.sh` (enctable.py); do not edit.\n\n")
    f.write("/// How an operand's value is made (`M68kMCCodeEmitter`'s `encode*`, or its register/immediate value).\n")
    f.write("#[derive(Clone, Copy, Debug)]\npub enum Enc {\n    Plain,\n    RelocImm(u8),\n    PcRelImm(u8),\n")
    f.write("    FpSysSelect,\n    InverseMoveMask,\n    Scale,\n    IndexSuppress,\n}\n\n")
    f.write("/// A field of the encoded instruction, `lo` bits above its first bit.\n")
    f.write("#[derive(Clone, Copy, Debug)]\npub enum Piece {\n    Const { lo: u16, width: u8, value: u64 },\n")
    f.write("    /// `width` bits of machine operand `at`, from its bit `from`.\n")
    f.write("    Operand { lo: u16, width: u8, at: u8, from: u8, enc: Enc },\n}\n\n")
    f.write("/// `(instruction name, width in bits, pieces)`, sorted by name.\n")
    f.write(f"pub static ENC: [(&str, u16, &[Piece]); {len(rows)}] = [\n")
    for name, width, pieces in rows:
        cells = []
        for kind, lo, w, *rest in pieces:
            if kind == "Const":
                cells.append(f"Piece::Const {{ lo: {lo}, width: {w}, value: {rest[0]} }}")
            else:
                at, frm, enc = rest
                cells.append(f"Piece::Operand {{ lo: {lo}, width: {w}, at: {at}, from: {frm}, enc: {enc} }}")
        f.write(f"    ({json.dumps(name)}, {width}, &[{', '.join(cells)}]),\n")
    f.write("];\n\n")
    f.write("pub fn encoding(name: &str) -> Option<&'static (&'static str, u16, &'static [Piece])> {\n")
    f.write("    ENC.binary_search_by_key(&name, |row| row.0).ok().map(|at| &ENC[at])\n}\n")
