#!/usr/bin/env python3
"""Reads the pin's `llvm-tblgen --dump-json` into the asm strings of a target's instructions.

    asmtable.py TARGET.json OUT.rs NAMESPACE

One row per instruction of the namespace: its name, its `AsmString` (tabs as `\\t`) and, for each
`$name` it uses, the machine operand it starts at and the instruction printer's method for it
(`printARID32Mem`, `printOperand`). An operand takes as many machine operands as its
`MIOperandInfo` has (one if none); the outputs come first, then the inputs.
"""
import json
import re
import sys

src, out, ns = sys.argv[1:4]
data = json.load(open(src))

rows = []
for name, inst in sorted(data.items()):
    if not (isinstance(inst, dict) and inst.get("Namespace") == ns and "AsmString" in inst):
        continue
    if "Instruction" not in inst.get("!superclasses", []):
        continue
    at, operands = 0, {}
    for arg in inst["OutOperandList"]["args"] + inst["InOperandList"]["args"]:
        cls = data[arg[0]["def"]]
        parts = cls.get("MIOperandInfo")
        width = max(1, len(parts["args"])) if isinstance(parts, dict) else 1
        if arg[1] is not None:
            operands[arg[1]] = (at, cls.get("PrintMethod") or "printOperand")
        at += width
    text = inst["AsmString"]
    used = []
    for ref in re.findall(r"\$\{?(\w+)\}?", text):
        if ref not in operands:
            raise SystemExit(f"{name}: {text!r} names ${ref}, which is no operand")
        used.append((ref, *operands[ref]))
    rows.append((name, text, used))

with open(out, "w") as f:
    f.write("//! The asm strings and operand printers of the pin's instructions.\n//!\n")
    f.write("//! Generated by `tools/dagisel/regen-target.sh` (asmtable.py); do not edit.\n\n")
    f.write("/// An operand an asm string names: its machine operand number and the printer method.\n")
    f.write("pub struct AsmOperand {\n    pub name: &'static str,\n    pub at: u8,\n    pub method: &'static str,\n}\n\n")
    f.write("/// `(instruction name, asm string, operands)`, sorted by name.\n")
    f.write(f"pub static ASM: [(&str, &str, &[AsmOperand]); {len(rows)}] = [\n")
    for name, text, used in rows:
        ops = ", ".join(f'AsmOperand {{ name: "{n}", at: {a}, method: "{m}" }}' for n, a, m in used)
        f.write(f"    ({json.dumps(name)}, {json.dumps(text)}, &[{ops}]),\n")
    f.write("];\n\n")
    f.write("pub fn asm(name: &str) -> Option<&'static (&'static str, &'static str, &'static [AsmOperand])> {\n")
    f.write("    ASM.binary_search_by_key(&name, |row| row.0).ok().map(|at| &ASM[at])\n}\n")
