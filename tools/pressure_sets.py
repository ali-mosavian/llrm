#!/usr/bin/env python3
"""The pin's x86 register pressure sets for a target's integer registers, as `pressure.sets`.

usage: pressure_sets.py <X86GenRegisterInfoTargetDesc.inc> <x86.json> <registers.regs>

The .inc (from the pin's build) gives the pressure sets, their raw limits, the largest class
of each set, each class's weight and its sets; the JSON (`llvm-tblgen --dump-json X86.td`)
gives each class's registers. Only the classes with a register the target describes are kept.
"""

import json
import re
import sys


def table(text, name):
    start = text.index(name)
    return text[text.index("{", start) + 1 : text.index("};", start)]


def members_of(classes, dag):
    """The registers of a class's `MemberList` dag, in order (`add`, `sub`, `and`, `sequence`)."""
    op = dag["operator"]["def"]
    args = [a[0] for a in dag["args"]]
    if op == "sequence":
        return [args[0] % n for n in range(args[1], args[2] + 1)]

    def one(arg):
        if isinstance(arg, dict) and arg.get("kind") == "dag":
            return members_of(classes, arg)
        name = arg["def"]
        if name in classes and "MemberList" in classes[name]:
            return members_of(classes, classes[name]["MemberList"])
        return [name]

    parts = [one(a) for a in args]
    if op == "add":
        return [m for part in parts for m in part]
    if op == "sub":
        return [m for m in parts[0] if all(m not in part for part in parts[1:])]
    if op == "and":
        return [m for m in parts[0] if all(m in part for part in parts[1:])]
    raise SystemExit(f"unhandled MemberList operator {op}")


def main(inc_path, json_path, regs_path):
    inc = open(inc_path).read()
    classes = json.load(open(json_path))
    visible = {
        line.split()[0].upper()
        for line in open(regs_path)
        if line.strip() and not line.startswith("#") and not line.startswith("@") and "int" in line.split()[4].split(",")
    }

    weights = [(int(a), int(b), n) for a, b, n in re.findall(r"\{(\d+), (\d+)\},\s*// (\w+)", table(inc, "RCWeightTable"))]
    sets = re.findall(r'\s"(\w+)",', table(inc, "PressureNameTable"))
    limits = [int(n) for n in re.findall(r"(\d+),\s*// \d+:", table(inc, "PressureLimitTable"))]
    largest = re.findall(r"X86::(\w+)RegClassID,\s*// \d+:", table(inc, "PSetRegClassTable"))
    flat = [int(n) for n in re.findall(r"-?\d+", re.sub(r"/\*.*?\*/", "", table(inc, "RCSetsTable")))]
    starts = [int(n) for n in re.findall(r"\d+", table(inc, "RCSetStartTable"))]
    assert len(sets) == len(limits) == len(largest) == 36, (len(sets), len(limits), len(largest))
    assert len(starts) == len(weights), (len(starts), len(weights))

    out = [
        "# x86 register pressure sets (generated by tools/pressure_sets.py from the pin's X86GenRegisterInfoTargetDesc.inc, d1106deb71cc).",
        "#",
        "#   set <index> <name> <limit> <largest class>   the raw limit, before the reserved registers are taken off",
        "#   class <name> <weight> <registers in the class> <sets, comma separated> <visible registers, comma separated>",
        "",
    ]
    for index, (name, limit, big) in enumerate(zip(sets, limits, largest)):
        out.append(f"set {index} {name} {limit} {big}")
    out.append("")
    for (weight, _, name), start in zip(weights, starts):
        if weight == 0 or name not in classes:
            continue
        members = members_of(classes, classes[name]["MemberList"])
        shown = [m.lower() for m in members if m in visible]
        if not shown:
            continue
        ids = []
        for n in flat[start:]:
            if n < 0:
                break
            ids.append(n)
        out.append(f"class {name} {weight} {len(members)} {','.join(map(str, ids)) or '-'} {','.join(shown)}")
    print("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:])
