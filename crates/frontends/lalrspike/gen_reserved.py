#!/usr/bin/env python3
"""Generate src/qb_reserved.rs: the words BC refuses as names, per family, from the oracle's verdicts.

    gen_reserved.py corpus/catalog.jsonl corpus/bc_results.json > src/qb_reserved.rs

A word is reserved as a name where `DIM word` is refused; as a field name where
`TYPE tt: word AS INTEGER: END TYPE` is.
"""
import json
import sys

FAMILIES = ("qb45", "pds71", "vbdos")
items = [json.loads(line) for line in open(sys.argv[1]) if '"group": "words"' in line]
bc = json.load(open(sys.argv[2]))
names = {f: set() for f in FAMILIES}
fields = {f: set() for f in FAMILIES}
types = {f: set() for f in FAMILIES}
for item in items:
    verdict = bc.get(str(item["id"]))
    if verdict is None:
        continue
    for family in FAMILIES:
        messages = verdict[family]
        if not messages or messages == ["CRASH"]:
            continue
        if item["pattern"] == "DIM {w}":
            names[family].add(item["text"][4:])
        elif item["pattern"] == "TYPE {w}: a AS INTEGER: END TYPE":
            if messages[0] == "Identifier expected":
                types[family].add(item["text"].split(": ")[0][5:])
        elif item["pattern"] == "TYPE tt: {w} AS INTEGER: END TYPE":
            word = item["text"].split(": ")[1].split(" AS ")[0]
            if messages[0] == "Identifier expected":
                fields[family].add(word)
print("//! Generated by gen_reserved.py from the real BC's verdicts on every reserved word used as a name.\n")
for label, table in (("NAMES", names), ("FIELDS", fields), ("TYPES", types)):
    for i, family in enumerate(FAMILIES):
        words = ", ".join(f'"{w}"' for w in sorted(table[family]))
        print(f"const {label}_{family.upper()}: &[&str] = &[{words}];\n")
print('''
fn family(dialect: qbfront::Dialect) -> usize {
    match dialect {
        qbfront::Dialect::QBasic11 | qbfront::Dialect::QuickBasic45 => 0,
        qbfront::Dialect::Pds71 => 1,
        qbfront::Dialect::VbDos | qbfront::Dialect::Quickr => 2,
    }
}

/// The name without its type character, but for `$`, which is part of the word's spelling (`LEFT$`).
fn spelled(name: &str) -> String {
    let upper = name.to_ascii_uppercase();
    if upper.ends_with('$') { upper } else { upper.trim_end_matches(['%', '&', '!', '#', '@']).to_owned() }
}

/// Whether BC refuses `name` as a variable, constant, parameter or procedure name.
pub fn is_reserved_name(dialect: qbfront::Dialect, name: &str) -> bool {
    let table = [NAMES_QB45, NAMES_PDS71, NAMES_VBDOS][family(dialect)];
    table.binary_search(&spelled(name).as_str()).is_ok()
}

/// Whether BC refuses `name` as a field of a record.
pub fn is_reserved_field(dialect: qbfront::Dialect, name: &str) -> bool {
    let table = [FIELDS_QB45, FIELDS_PDS71, FIELDS_VBDOS][family(dialect)];
    table.binary_search(&spelled(name).as_str()).is_ok()
}

/// Whether BC refuses `name` as the name of a record type.
pub fn is_reserved_type(dialect: qbfront::Dialect, name: &str) -> bool {
    let table = [TYPES_QB45, TYPES_PDS71, TYPES_VBDOS][family(dialect)];
    table.binary_search(&spelled(name).as_str()).is_ok()
}''')
