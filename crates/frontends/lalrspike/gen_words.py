#!/usr/bin/env python3
"""Generate src/qb_words.rs: the reserved words of qbasbnf.prs as a case-insensitive logos DFA.

    gen_words.py ../qbfront/grammar/qbasbnf.prs > src/qb_words.rs
"""
import re
import sys

text = re.sub(r"/\*.*?\*/", " ", open(sys.argv[1]).read(), flags=re.S).split("Statements:")[0]
entries = re.findall(r'\b(tk\w+)\s*\(\s*"((?:[^"\\]|\\.)*)"', text)
words = [(name, spelling) for name, spelling in entries if re.fullmatch(r"[A-Za-z]+\$?", spelling)]
print("//! Generated by gen_words.py from the reserved words of `qbasbnf.prs`.\n")
print("use logos::Logos;\n")
print("#[derive(Logos, Clone, Copy, Debug, PartialEq, Eq)]\n#[allow(non_camel_case_types)]\npub enum Word {")
for name, spelling in words:
    print(f'    #[token("{spelling}", ignore(case))]\n    {name[2:]},')
print("}\n")
print("/// The grammar's token name of each word, in the enum's order.")
print("pub const NAMES: &[&str] = &[")
for name, _ in words:
    print(f'    "{name}",')
print("];")
