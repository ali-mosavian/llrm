#!/usr/bin/env python3
"""Generate src/qb_classes.rs: the grammar's keyword sets as a class bitmask per Kw.

    gen_classes.py src/qb.lalrpop > src/qb_classes.rs
"""
import re
import sys

text = open(sys.argv[1]).read()
SETS = ["Fn0", "Fn1", "Fn2", "Fn23", "FnBound", "FnRef", "FnWord", "AnyWord", "CtxWord", "DataFirst", "DataRest", "ObjWord", "Fn0Var"]
# the extern block names every keyword: "tkABS" => Tok::Kw(Kw::ABS)
variants = dict(re.findall(r'"(tk\w+)" => Tok::Kw\(Kw::(\w+)\)', text))
print("//! Generated by gen_classes.py from the keyword sets of `qb.lalrpop`.\n")
print("use crate::qb_kw::Kw;\n")
for bit, name in enumerate(SETS):
    print(f"pub const {re.sub(r'(?<!^)(?=[A-Z])', '_', name).upper()}: u16 = 1 << {bit};")
print("\nconst fn build() -> [u16; 512] {\n    let mut table = [0; 512];")
for name in SETS:
    m = re.search(rf"^{name}: Tok = \{{(.*?)\}};", text, re.S | re.M)
    const = re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()
    names = re.findall(r'"(tk\w+)"', m.group(1))
    for tk in names:
        print(f"    table[Kw::{variants[tk]} as usize] |= {const};")
print("    table\n}\n")
print("static TABLE: [u16; 512] = build();\n")
print("pub fn class(kw: Kw) -> u16 {\n    TABLE[kw as usize]\n}")
