#!/usr/bin/env bash
# Regenerates src/dagisel/generated. The pin build has no WebAssembly target, so the headers the ids need
# (WebAssembly*Gen*.inc) are made here with the pin's tblgen into a stand-in build directory.
set -euo pipefail

LLVM_SRC=${LLVM_SRC:-$HOME/scratch/llvm-src}
PIN_BUILD=${PIN_BUILD:-$HOME/scratch/llvm-build}
ROOT=$(cd "$(dirname "$0")/../../.." && pwd)
B=$(mktemp -d); trap 'rm -rf "$B"' EXIT
T=$LLVM_SRC/llvm/lib/Target/WebAssembly
G=$B/lib/Target/WebAssembly
mkdir -p "$B/bin" "$G"
ln -s "$PIN_BUILD/bin/llvm-tblgen" "$B/bin/llvm-tblgen"
ln -s "$PIN_BUILD/include" "$B/include"
for gen in "instr-info:InstrInfo" "register-info:RegisterInfo" "sd-node-info:SDNodeInfo" "subtarget:SubtargetInfo"; do
  "$B/bin/llvm-tblgen" "-gen-${gen%%:*}" -I"$LLVM_SRC/llvm/include" -I"$LLVM_SRC/llvm/lib/Target" -I"$T" \
    "$T/WebAssembly.td" -o "$G/WebAssemblyGen${gen##*:}.inc"
done
LLVM_BUILD=$B "$ROOT/tools/dagisel/regen-target.sh" "$ROOT/crates/target/llrm-wasm/dagisel.toml" "$@"

# The opcodes the post-selection passes build; no selection pattern names them, so the table's ids omit them.
{
  echo "//! Machine opcodes the post-selection passes build, from \`WebAssemblyGenInstrInfo.inc\`. Generated by regen.sh."
  echo
  grep -E '^\s+((DROP|COPY|TEE|LOCAL_TEE)_(I32|I64|F32|F64)|END_FUNCTION|BLOCK|LOOP|END_BLOCK|END_LOOP|CALL|CALL_PARAMS|CALL_RESULTS|CALL_INDIRECT|RET_CALL|RET_CALL_RESULTS|RET_CALL_INDIRECT) ' "$G/WebAssemblyGenInstrInfo.inc" |
    sed -E 's/^\s+([A-Za-z0-9_]+)\s*= ([0-9]+),.*/pub const \1: u16 = \2;/'
} > "$ROOT/crates/target/llrm-wasm/src/dagisel/post_ids.rs"

# The stack form of every opcode (its NAME_S record): string, operands, opcode bits; for the printer and the encoder.
"$B/bin/llvm-tblgen" -dump-json -I"$LLVM_SRC/llvm/include" -I"$LLVM_SRC/llvm/lib/Target" -I"$T" "$T/WebAssembly.td" -o "$B/wasm.json"
python3 -I - "$B/wasm.json" "$G/WebAssemblyGenInstrInfo.inc" "$ROOT/crates/target/llrm-wasm/src/asm_strings.rs" <<'PY'
import json, re, sys
records = json.load(open(sys.argv[1]))
ids = {m.group(1): int(m.group(2)) for m in re.finditer(r"^\s+(\w+)\s*= (\d+),", open(sys.argv[2]).read(), re.M)}
def operands(name):
    return [(arg[1], arg[0]["def"]) for arg in records[name]["InOperandList"]["args"]]
def binary(name):
    return sum(bit << i for i, bit in enumerate(records[name]["Inst"]) if bit in (0, 1))
rows = sorted((ids[n], records[n + "_S"]["AsmString"], operands(n + "_S"), binary(n + "_S")) for n in ids if n + "_S" in records and records[n + "_S"]["AsmString"])
with open(sys.argv[3], "w") as out:
    out.write("//! The stack-form assembly string of each opcode (`NAME_S`). Generated by regen.sh.\n\n")
    out.write("""/// One opcode's stack form: its string, its immediate operands (name and operand class) and its
/// opcode bits (a prefix byte above the low byte).
pub struct Asm {
    pub opcode: u16,
    pub text: &'static str,
    pub names: &'static [&'static str],
    pub kinds: &'static [&'static str],
    pub binary: u32,
}

pub fn find(opcode: u16) -> Option<&'static Asm> {
    ASM_STRINGS.iter().find(|a| a.opcode == opcode)
}

""")
    out.write("pub const ASM_STRINGS: &[Asm] = &[\n")
    for opcode, text, ops, code in rows:
        names = ", ".join(json.dumps(n) for n, _ in ops)
        kinds = ", ".join(json.dumps(k) for _, k in ops)
        out.write("    Asm { opcode: %d, text: %s, names: &[%s], kinds: &[%s], binary: %#x },\n" % (opcode, json.dumps(text), names, kinds, code))
    out.write("];\n")
PY
