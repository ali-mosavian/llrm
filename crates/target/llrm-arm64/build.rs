//! Generates arm64's register ids and `REGISTER_INFO` from its
//! `registers.regs`.

fn main() {
    let path = "src/registers.regs";
    println!("cargo:rerun-if-changed={path}");
    let text = std::fs::read_to_string(path).expect("registers.regs");
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let ids = llrm_target::registers::constants(&text, "RegId").unwrap_or_else(|error| panic!("{path}: {error}"));
    std::fs::write(out.join("register_ids.rs"), ids).unwrap();
    let info = llrm_target::registers::source_with(&text, "RegId", "reg", &llrm_lir::registers::CLASSES, "rows")
        .unwrap_or_else(|error| panic!("{path}: {error}"));
    std::fs::write(out.join("register_info.rs"), info).unwrap();
    // The rows the shared passes read, from the opcode file: kinds, ties,
    // flags.
    let (dialect_path, opcodes_path) = ("src/instructions/dialect.toml", "src/instructions/opcodes.instr");
    println!("cargo:rerun-if-changed={dialect_path}");
    println!("cargo:rerun-if-changed={opcodes_path}");
    let dialect = llrm_target::instr::Dialect::parse(&std::fs::read_to_string(dialect_path).expect("dialect.toml"))
        .unwrap_or_else(|error| panic!("{error}"));
    let opcodes =
        llrm_target::instr::parse_opcodes(&std::fs::read_to_string(opcodes_path).expect("opcodes.instr"), &dialect)
            .unwrap_or_else(|error| panic!("{error}"));
    let rows = llrm_target::instr::rows_source(
        opcodes.iter().map(|one| &one.form),
        "// @generated by build.rs from opcodes.instr.\nuse llrm_lir::registers::Row;\n\n",
    );
    std::fs::write(out.join("opcode_rows.rs"), rows).unwrap();
}
