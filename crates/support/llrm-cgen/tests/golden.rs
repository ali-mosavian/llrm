fn hashes(options: Options) -> Vec<u64> {
    (0..140).map(|seed| fnv(&program(seed, &options))).collect()
}

/// Moving the generator out of the 6502 test must not change a program: every
/// seed there was a regression found by one of these texts.
#[test]
fn the_cc65_model_generates_the_programs_the_6502_test_did() {
    let model = Options::new(DataModel::INT16);
    assert_eq!(hashes(model), DEFAULT);
    assert_eq!(hashes(Options { opaque: true, ..model }), OPAQUE);
    assert_eq!(hashes(Options { opaque: true, signed: false, ..model }), OPAQUE_UNSIGNED);
}

/// A 32-bit `int` has no `unsigned` that is 16 bits wide: the checksum, the
/// struct's word and the 16-bit type are `unsigned short`, the signed view of a
/// word is `short`.
#[test]
fn the_32_bit_model_names_its_16_bit_types() {
    let text = program(3, &Options::new(DataModel::INT32));
    assert!(text.contains("unsigned short ck"), "{text}");
    assert!(text.contains("struct S { unsigned char a; unsigned short b;"));
    assert!(!text.contains("(int)") && !text.contains("unsigned ck"));
}

/// A corpus with `walks` on has the pointer loops, and with it off none: a
/// differential test of a backend's post-increment loads that never saw one
/// would agree with anything.
#[test]
fn the_walks_option_adds_pointer_loops_and_only_then() {
    let model = Options::new(DataModel::INT32);
    let with = |walks| (0..300).filter(|seed| program(*seed, &Options { walks, ..model }).contains("*w++")).count();
    assert_eq!(with(false), 0);
    assert!(with(true) >= 60, "{} of 300 programs walk a pointer", with(true));
}
