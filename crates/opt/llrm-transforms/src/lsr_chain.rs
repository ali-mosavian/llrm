//! IV chains of LLVM's loop strength reduction (`IVInc`, `IVChain`,
//! `ChainInstruction`, `CollectChains`, `isProfitableChain`,
//! `isHighCostExpansion` and their helpers; LoopStrengthReduce.cpp at
//! `d1106deb71cc`, l.1134-1210, 2136-2176 and 2957-3560).
//!
//! # How it works
//! Walking the instructions from the header to the latch in program order,
//! each IV user that is not part of another expression is chained to an earlier
//! user whose IV operand it differs from by a loop-invariant increment:
//! `a[i]`, `a[i + x]`, `a[i + 2x]`. A chain materializes each user's operand
//! from the previous one with an add, so one register walks the chain instead
//! of a register per user. A chain is kept only if nothing else reads the IVs
//! across the increments and it saves registers (`isProfitableChain`). The
//! users in a kept chain are not fixups of the solver: [`Chains::inc_set`]
//! lists their operands.
//!
//! # Example
//! `x = a[i]; y = a[i + n]; z = a[i + 2n]` in a loop: three IV operands one
//! increment `n` apart become `p`, `p + n`, `p + n + n`: one chain of three.
//!
//! # Runs
//! Before the collection, from [`crate::lsr_pass`]; generated by
//! [`crate::lsr_implement`].
//!
//! # Limits
//! DEVIATE: `TTI.isProfitableLSRChainElement` is not asked (x86 says no); a
//! vector extract and `setChainedPhi` (the expander is not told which phis end
//! a chain) are not ported.

use llrm_analysis::scev::expr::{Kind, Scev, Type, Use as ScevUse};
use llrm_analysis::scev::{Cx, ScalarEvolution};
use llrm_mir::dense::IdSet;
use llrm_mir::module::{BlockId, InstId, Operand, ValueDef};
use llrm_mir::opcode::{CastOp, Opcode};
use llrm_support::hash::HashSet;

use crate::ivusers::IvUsers;
use crate::lsr_use::is_existing_phi;

/// `MaxChains`.
const MAX_CHAINS: usize = 8;

/// One increment of a chain: an IV user, the IV operand of it, and how the
/// operand differs from the previous link's.
#[derive(Clone, Debug)]
pub struct IvInc {
    pub user: InstId,
    pub iv_operand: Operand,
    pub inc_expr: Scev,
}

/// `IVChain`.
#[derive(Clone, Debug)]
pub struct IvChain {
    pub incs: Vec<IvInc>,
    pub expr_base: Option<Scev>,
}

impl IvChain {
    /// `hasIncs`.
    pub fn has_incs(&self) -> bool {
        self.incs.len() >= 2
    }

    /// `tailUserInst`.
    pub fn tail_user(&self) -> InstId {
        self.incs.last().expect("a chain has a head").user
    }

    /// The increments after the head (`IVChain::begin()`).
    pub fn rest(&self) -> &[IvInc] {
        &self.incs[1..]
    }
}

/// What the collection found: the chains, and the operands they take over (an
/// instruction and the index of the operand).
#[derive(Clone, Debug, Default)]
pub struct Chains {
    pub chains: Vec<IvChain>,
    pub inc_set: HashSet<(InstId, usize)>,
}

/// Near and far users of a chain: far ones cross an increment.
#[derive(Default)]
struct ChainUsers {
    far: IdSet<InstId>,
    near: IdSet<InstId>,
}

/// `getWideOperand`: through a truncate.
pub fn wide_operand(
    cx: &Cx,
    oper: Operand,
) -> Operand {
    if let Operand::Value(v) = oper
        && let ValueDef::Instruction(def) = cx.function.value(v).def
    {
        let instruction = cx.function.instruction(def);
        if instruction.opcode == Opcode::Cast(CastOp::Trunc) {
            return instruction.operands[0];
        }
    }
    oper
}

/// `findIVOperand`: the first operand of `inst` from `from` that is an
/// instruction computed by an add recurrence of loop `l`.
pub fn find_iv_operand(
    se: &mut ScalarEvolution,
    cx: &Cx,
    l: BlockId,
    inst: InstId,
    from: usize,
) -> Option<usize> {
    let operands = &cx.function.instruction(inst).operands;
    for (at, &operand) in operands.iter().enumerate().skip(from) {
        let Operand::Value(v) = operand else { continue };
        if !matches!(cx.function.value(v).def, ValueDef::Instruction(_)) || !se.is_value_scevable(cx, operand) {
            continue;
        }
        let s = se.get_scev(cx, operand);
        if se.addrec_header(s) == Some(l) {
            return Some(at);
        }
    }
    None
}

/// `getExprBase`: an approximation of the expression's base, none for a
/// constant; the rightmost operand, since the rightmost unknown is the pointer.
fn expr_base(
    se: &ScalarEvolution,
    s: Scev,
) -> Option<Scev> {
    match se.node(s).kind.clone() {
        Kind::Constant(_) => None,
        Kind::Truncate(op) | Kind::ZeroExtend(op) | Kind::SignExtend(op) => expr_base(se, op.scev),
        Kind::Add(ops) => {
            // Skip scaled operands, to follow adds as long as nothing is more
            // complex.
            for sub in ops.iter().rev() {
                match se.scev_type(sub.scev) {
                    Type::Add => return expr_base(se, sub.scev),
                    Type::Mul => {}
                    _ => return Some(sub.scev),
                }
            }
            Some(s)
        }
        Kind::AddRec(ops, _) => expr_base(se, ops[0].scev),
        _ => Some(s),
    }
}

/// `isHighCostExpansion`: whether expanding `s` is likely to cost much. Adds,
/// multiplication by a constant, and add recurrences of existing phis are fine.
fn is_high_cost_expansion(
    se: &mut ScalarEvolution,
    cx: &Cx,
    s: Scev,
    processed: &mut HashSet<Scev>,
) -> bool {
    match se.node(s).kind.clone() {
        Kind::Unknown(_) | Kind::Constant(_) => return false,
        Kind::Truncate(op) | Kind::ZeroExtend(op) | Kind::SignExtend(op) => {
            return is_high_cost_expansion(se, cx, op.scev, processed);
        }
        _ => {}
    }
    if !processed.insert(s) {
        return false;
    }
    match se.node(s).kind.clone() {
        Kind::Add(ops) => {
            for op in ops {
                if is_high_cost_expansion(se, cx, op.scev, processed) {
                    return true;
                }
            }
            return false;
        }
        Kind::Mul(ops) if ops.len() == 2 => {
            let (op0, op1) = (ops[0].scev, ops[1].scev);
            // Multiplication by a constant is fine.
            if se.as_constant(op0).is_some() {
                return is_high_cost_expansion(se, cx, op1, processed);
            }
            // If an existing multiplication makes this expression, fine.
            if let Some(Operand::Value(v)) = se.unknown_value(op1) {
                let users: Vec<InstId> = cx.function.users(v).iter().map(|u| u.user).collect();
                for user in users {
                    let instruction = cx.function.instruction(user);
                    if instruction.opcode == Opcode::Binary(llrm_mir::opcode::BinaryOp::Mul)
                        && let Some(result) = instruction.result
                        && se.is_value_scevable(cx, Operand::Value(result))
                    {
                        return se.get_scev(cx, Operand::Value(result)) != s;
                    }
                }
            }
        }
        Kind::AddRec(..) if is_existing_phi(se, cx, s) => return false,
        _ => {}
    }
    // Any other (div, mul, min, max) is high cost for now.
    true
}

impl IvChain {
    /// `isProfitableIncrement`: whether `inc_expr` is cheap enough to be kept
    /// in a register as a loop invariant.
    fn is_profitable_increment(
        &self,
        se: &mut ScalarEvolution,
        cx: &Cx,
        oper_expr: Scev,
        inc_expr: Scev,
    ) -> bool {
        // A constant offset from the head is not replaced by a variable
        // increment.
        if se.as_constant(inc_expr).is_none() {
            let head = wide_operand(cx, self.incs[0].iv_operand);
            let head_expr = se.get_scev(cx, head);
            let diff = se.get_minus_scev(cx, ScevUse::of(oper_expr), ScevUse::of(head_expr), 0, 0);
            if se.as_constant(diff).is_some() {
                return false;
            }
        }
        let mut processed = HashSet::default();
        !is_high_cost_expansion(se, cx, inc_expr, &mut processed)
    }
}

/// `isProfitableChain`: whether the chain saves registers: nothing else reads
/// the IVs across it, and its increments cost less than the registers of the
/// users they replace.
fn is_profitable_chain(
    se: &mut ScalarEvolution,
    cx: &Cx,
    chain: &IvChain,
    far_users: &IdSet<InstId>,
) -> bool {
    if !chain.has_incs() || !far_users.is_empty() {
        return false;
    }
    // The chain itself may need a register.
    let mut cost: i64 = 1;
    // A complete chain likely removes the need to keep the original IV: it
    // ends in a header phi that is the head's increment.
    if cx.function.instruction(chain.tail_user()).opcode == Opcode::Phi
        && let Some(result) = cx.function.instruction(chain.tail_user()).result
        && se.get_scev(cx, Operand::Value(result)) == chain.incs[0].inc_expr
    {
        cost -= 1;
    }
    let mut last: Option<Scev> = None;
    let (mut constants, mut variables, mut reused) = (0, 0, 0);
    for inc in chain.rest() {
        if se.match_zero(inc.inc_expr) {
            continue;
        }
        // A constant increment is neutral: it folds into an address or an add.
        if se.as_constant(inc.inc_expr).is_some() {
            constants += 1;
            continue;
        }
        if Some(inc.inc_expr) == last {
            reused += 1;
        } else {
            variables += 1;
        }
        last = Some(inc.inc_expr);
    }
    // One increment is LSR's post-inc use; several keep the IV live longer.
    if constants > 1 {
        cost -= 1;
    }
    // Increments that did not exist in the loop may cost a register.
    cost += variables;
    // Reusing a variable increment saves the register for the multiple.
    cost -= reused;
    cost < 0
}

/// `CollectChains`: the profitable chains of the IV users of loop `l`. `stress`
/// is LLVM's `-lsr-stress-ivchain`: every chain, to test the generation.
pub fn collect_chains(
    se: &mut ScalarEvolution,
    cx: &Cx,
    l: BlockId,
    users: &IvUsers,
    is_ephemeral: &dyn Fn(InstId) -> bool,
    stress: bool,
) -> Chains {
    let function = cx.function;
    let lp = cx.loops.get_loop_for(l).expect("a loop");
    let latch = lp.get_loop_latch(function).expect("a latch");
    // The path from the header to the latch down the dominator tree.
    let mut path = vec![];
    let mut rung = latch;
    while rung != l {
        path.push(rung);
        let Some(up) = cx.tree.immediate_dominator(rung) else { break };
        rung = up;
    }
    path.push(l);

    let mut chains: Vec<IvChain> = Vec::new();
    let mut chain_users: Vec<ChainUsers> = Vec::new();
    for &block in path.iter().rev() {
        let insts: Vec<InstId> = function.iter_block(block).collect();
        for inst in insts {
            let instruction = function.instruction(inst);
            // Instructions the IV users analysis did not see.
            if instruction.opcode == Opcode::Phi || !users.is_iv_user_or_operand(inst) {
                continue;
            }
            if is_ephemeral(inst) {
                continue;
            }
            // Only leaf users: not part of a SCEV expression.
            if let Some(result) = instruction.result
                && se.is_value_scevable(cx, Operand::Value(result))
            {
                let s = se.get_scev(cx, Operand::Value(result));
                if se.scev_type(s) != Type::Unknown {
                    continue;
                }
            }
            for u in chain_users.iter_mut() {
                u.near.remove(&inst);
            }
            // Operands that can be chained.
            let mut unique = IdSet::<InstId>::new();
            let mut from = 0;
            while let Some(at) = find_iv_operand(se, cx, l, inst, from) {
                from = at + 1;
                let Operand::Value(v) = function.instruction(inst).operands[at] else { continue };
                let ValueDef::Instruction(oper) = function.value(v).def else { continue };
                if unique.insert(oper) {
                    chain_instruction(se, cx, l, users, inst, oper, &mut chains, &mut chain_users, stress);
                }
            }
        }
    }
    // The phi backedges: whether a chain can generate the IV's post-inc.
    let phis: Vec<InstId> =
        function.iter_block(l).take_while(|&inst| function.instruction(inst).opcode == Opcode::Phi).collect();
    for phi in phis {
        let Some(result) = function.instruction(phi).result else { continue };
        if !se.is_value_scevable(cx, Operand::Value(result)) {
            continue;
        }
        let incoming = function
            .instruction(phi)
            .operands
            .chunks(2)
            .find_map(
                |pair| match pair[1] {
                    Operand::Block(from) if from == latch => Some(pair[0]),
                    _ => None,
                },
            );
        if let Some(Operand::Value(v)) = incoming
            && let ValueDef::Instruction(inc) = function.value(v).def
        {
            chain_instruction(se, cx, l, users, phi, inc, &mut chains, &mut chain_users, stress);
        }
    }

    // The unprofitable chains go.
    let mut kept = Chains::default();
    for (chain, chain_users) in chains.into_iter().zip(&chain_users) {
        if !stress && !is_profitable_chain(se, cx, &chain, &chain_users.far) {
            continue;
        }
        // The operands of the chain's increments (not its head) are taken over.
        for inc in chain.rest() {
            let at = function
                .instruction(inc.user)
                .operands
                .iter()
                .position(|&operand| operand == inc.iv_operand)
                .expect("cannot find IV operand");
            kept.inc_set.insert((inc.user, at));
        }
        kept.chains.push(chain);
    }
    kept
}

/// `ChainInstruction`: `user_inst` joins an existing chain whose last IV
/// operand it differs from by a profitable loop-invariant increment, or heads a
/// new one.
#[allow(clippy::too_many_arguments)]
fn chain_instruction(
    se: &mut ScalarEvolution,
    cx: &Cx,
    l: BlockId,
    users: &IvUsers,
    user_inst: InstId,
    iv_oper: InstId,
    chains: &mut Vec<IvChain>,
    chain_users: &mut Vec<ChainUsers>,
    stress: bool,
) {
    let function = cx.function;
    let iv_operand = Operand::Value(function.instruction(iv_oper).result.expect("an IV operand value"));
    // IVs used at several widths are generally widened, with narrow uses under
    // a free truncate.
    let next_iv = wide_operand(cx, iv_operand);
    let oper_expr = se.get_scev(cx, next_iv);
    let oper_expr_base = expr_base(se, oper_expr);
    let user_is_phi = function.instruction(user_inst).opcode == Opcode::Phi;

    // The existing chains: can the operand be a profitable invariant increment
    // from the last link?
    let mut found: Option<(usize, Scev)> = None;
    for (idx, chain) in chains.iter().enumerate() {
        // Same unscaled base, or the minus below could not cancel it.
        if !stress && chain.expr_base != oper_expr_base {
            continue;
        }
        let prev_iv = wide_operand(cx, chain.incs.last().expect("a head").iv_operand);
        if function.operand_type(cx.context, prev_iv) != function.operand_type(cx.context, next_iv) {
            continue;
        }
        // A phi ends a chain.
        if user_is_phi && function.instruction(chain.tail_user()).opcode == Opcode::Phi {
            continue;
        }
        // The increment must be loop invariant to live in a register.
        let prev_expr = se.get_scev(cx, prev_iv);
        let inc_expr = se.get_minus_scev(cx, ScevUse::of(oper_expr), ScevUse::of(prev_expr), 0, 0);
        if se.is_could_not_compute(inc_expr) || !se.is_loop_invariant(cx, inc_expr, Some(l)) {
            continue;
        }
        if stress || chain.is_profitable_increment(se, cx, oper_expr, inc_expr) {
            found = Some((idx, inc_expr));
            break;
        }
    }
    let (chain_idx, last_inc_expr) = match found {
        Some(found) => {
            chains[found.0].incs.push(IvInc { user: user_inst, iv_operand, inc_expr: found.1 });
            found
        }
        None => {
            // A new chain, unless there are too many; not for a phi, which must
            // be last.
            if user_is_phi || (chains.len() >= MAX_CHAINS && !stress) {
                return;
            }
            // IV users may have skipped sign or zero extensions: no chains
            // through extensions unless hoisted into this loop's recurrence.
            if se.addrec_header(oper_expr).is_none() {
                return;
            }
            chains.push(IvChain {
                incs: vec![IvInc { user: user_inst, iv_operand, inc_expr: oper_expr }],
                expr_base: oper_expr_base,
            });
            chain_users.push(ChainUsers::default());
            (chains.len() - 1, oper_expr)
        }
    };
    let chain = &chains[chain_idx];
    let cu = &mut chain_users[chain_idx];
    // This chain's near users become far ones.
    if !se.match_zero(last_inc_expr) {
        let near: Vec<InstId> = cu.near.iter().collect();
        cu.near.clear();
        for inst in near {
            cu.far.insert(inst);
        }
    }
    // All other users of the IV operand become near users of the chain; the
    // chain's own users do not count.
    let operand_value = function.instruction(iv_oper).result.expect("an IV operand value");
    let other_users: Vec<InstId> = function.users(operand_value).iter().map(|u| u.user).collect();
    for other in other_users {
        if chain.incs.iter().any(|inc| inc.user == other) {
            continue;
        }
        let instruction = function.instruction(other);
        if let Some(result) = instruction.result
            && se.is_value_scevable(cx, Operand::Value(result))
            && users.is_iv_user_or_operand(other)
        {
            let s = se.get_scev(cx, Operand::Value(result));
            if se.scev_type(s) != Type::Unknown {
                continue;
            }
        }
        cu.near.insert(other);
    }
    // This user is part of the chain: no longer a use of it.
    cu.far.remove(&user_inst);
}
