/// What `compute_known_bits_from_context` adds to a `freeze`'s operand at the
/// `freeze`, one line per `freeze` in `vtdump` format. LLVM's `kb` of a
/// `freeze` is its operand's, so the expected lines are
/// `tools/llvmport/vtdump.sh kb`.
fn context_lines(text: &str) -> String {
    let module = parse::module(text).expect("parses");
    let layout = DataLayout::default();
    let mut out = String::new();
    for global in &module.globals {
        let GlobalKind::Function(function) = &global.kind else { continue };
        if function.is_declaration() {
            continue;
        }
        let dt = DomTree::of(function);
        let assumptions = AssumptionCache::new(&module, function);
        let mut n = function.parameters().len();
        for (_, inst) in function.walk() {
            let instruction = function.instruction(inst);
            if instruction.result.is_none() {
                continue;
            }
            if instruction.opcode == Opcode::Freeze {
                let mut q = Query::new(&module, function, &layout).with_cxt(Some(inst));
                q.dt = Some(&dt);
                q.assumptions = Some(&assumptions);
                let v: Operand = instruction.operands[0];
                let mut known = KnownBits::unknown(q.scalar_bits(v));
                compute_known_bits_from_context(&q, v, &mut known, 0);
                out += &format!("{} {n} kb={}\n", global.name.as_deref().unwrap_or(""), known.print());
            }
            n += 1;
        }
    }
    out
}

