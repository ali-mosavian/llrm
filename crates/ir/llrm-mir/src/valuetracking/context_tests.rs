/// `computeKnownBits` of the values a `select` or `br` condition tells of, and
/// of a select's arms, under `CondContext(cond, invert)`: the lines of
/// `ctxdump`'s `cc` mode.
fn cond_context_lines(text: &str) -> String {
    let module = parse::module(text).expect("parses");
    let layout = DataLayout::default();
    let mut out = String::new();
    for global in &module.globals {
        let GlobalKind::Function(function) = &global.kind else { continue };
        if function.is_declaration() {
            continue;
        }
        let name = global.name.as_deref().unwrap_or("");
        let dt = DomTree::of(function);
        let assumptions = AssumptionCache::new(&module, function);
        let insts: Vec<_> = function.walk().map(|(_, inst)| inst).collect();
        let nm = |v: Operand| -> String {
            let Operand::Value(id) = v else { return "?".into() };
            match function.value(id).def {
                crate::module::ValueDef::Argument(k) => format!("a{k}"),
                crate::module::ValueDef::Instruction(i) => {
                    format!("i{}", insts.iter().position(|one| *one == i).expect("placed"))
                }
            }
        };
        for (at, &u) in insts.iter().enumerate() {
            let instruction = function.instruction(u);
            let c = match instruction.opcode {
                Opcode::Select => instruction.operands[0],
                Opcode::Br if instruction.operands.len() == 3 => instruction.operands[0],
                _ => continue,
            };
            let mut base = Query::new(&module, function, &layout).with_cxt(Some(u));
            base.dt = Some(&dt);
            base.assumptions = Some(&assumptions);
            let mut cc = CondContext::new(c);
            find_values_affected_by_condition(&base, c, false, &mut |v| {
                cc.affected_values.insert(v);
            });
            for invert in [false, true] {
                cc.invert = invert;
                let q = base.with_cond_context(&cc);
                let mut vals: Vec<Operand> = cc.affected_values.iter().copied().collect();
                if instruction.opcode == Opcode::Select {
                    vals.extend([instruction.operands[1], instruction.operands[2]]);
                }
                let mut named: Vec<(String, Operand)> = Vec::new();
                for v in vals {
                    let bits = q.scalar_bits(v);
                    if bits == 0 || bits > 128 || !matches!(v, Operand::Value(_)) {
                        continue;
                    }
                    if !named.iter().any(|(n, _)| *n == nm(v)) {
                        named.push((nm(v), v));
                    }
                }
                named.sort_by(|a, b| a.0.cmp(&b.0));
                for (n, v) in named {
                    out += &format!(
                        "{name} cc {} i{at} {} {n} kb={}\n",
                        nm(c),
                        u8::from(invert),
                        compute_known_bits(&q, v, 0).print()
                    );
                }
            }
        }
    }
    out
}

