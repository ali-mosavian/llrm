//! `generated/ids.rs`: the pin's numbers for the node opcodes and value types.

use std::fmt::Write as _;

use crate::inc::Ids;

const KEYWORDS: &[&str] = &["as", "break", "const", "continue", "else", "enum", "false", "fn", "for", "if", "in", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while"];

fn constant_name(name: &str) -> String {
    if KEYWORDS.contains(&name) { format!("r#{name}") } else { name.to_string() }
}

/// `extras` are the symbols `tools/dagisel/extra_symbols.txt` asks for; only those of `X86::` (the
/// 18,000 instruction and register numbers) are written.
pub fn render(ids: &Ids, extras: &[String]) -> String {
    let mut out = String::from(
        "//! The pin's numbers for the node opcodes and value types the matcher table names.\n//!\n//! Generated by `tools/dagisel/regen.sh`; do not edit.\n\n#![allow(non_upper_case_globals)]\n\nuse crate::matcher::Vt;\n",
    );
    for (module, prefix, is_vt) in [("isd", "ISD::", false), ("x86isd", "X86ISD::", false), ("x86", "X86::", false), ("target_opcode", "TargetOpcode::", false), ("mvt", "MVT::", true)] {
        writeln!(out, "\npub mod {module} {{").unwrap();
        if is_vt {
            writeln!(out, "    use super::Vt;").unwrap();
        }
        let mut names: Vec<_> = ids
            .0
            .iter()
            .filter(|(n, _)| n.starts_with(prefix) && (prefix != "X86::" || extras.contains(n)))
            .collect();
        names.sort();
        for (name, value) in names {
            let name = constant_name(&name[prefix.len()..]);
            if is_vt {
                writeln!(out, "    pub const {name}: Vt = Vt({value});").unwrap();
            } else {
                writeln!(out, "    pub const {name}: u16 = {value};").unwrap();
            }
        }
        writeln!(out, "}}").unwrap();
    }
    out
}
