//! `generated/ids.rs`: the pin's numbers for the node opcodes and value types.

use std::fmt::Write as _;

use crate::inc::Ids;

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "else", "enum", "false", "fn", "for", "if", "in", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where",
    "while",
];

fn constant_name(name: &str) -> String {
    if KEYWORDS.contains(&name) { format!("r#{name}") } else { name.to_string() }
}

/// `extras` are the symbols `tools/dagisel/extra_symbols.txt` asks for; only
/// those of `X86::` (the 18,000 instruction and register numbers) are written.
pub fn render(
    ids: &Ids,
    extras: &[String],
    instructions: &std::collections::BTreeSet<String>,
) -> String {
    let mut out = String::from(
        "//! The pin's numbers for the node opcodes and value types the matcher table names.\n//!\n//! Generated by `tools/dagisel/regen.sh`; do not edit.\n\n#![allow(non_upper_case_globals)]\n\nuse crate::matcher::Vt;\n",
    );
    for (module, prefix, is_vt) in [
        ("isd", "ISD::", false),
        ("x86isd", "X86ISD::", false),
        ("x86", "X86::", false),
        ("target_opcode", "TargetOpcode::", false),
        ("mvt", "MVT::", true),
    ] {
        writeln!(out, "\npub mod {module} {{").unwrap();
        if is_vt {
            writeln!(out, "    use super::Vt;").unwrap();
        }
        let mut names: Vec<_> =
            ids.0.iter().filter(|(n, _)| n.starts_with(prefix) && (prefix != "X86::" || extras.contains(n))).collect();
        names.sort();
        for (name, value) in names {
            let name = constant_name(&name[prefix.len()..]);
            if is_vt {
                writeln!(out, "    pub const {name}: Vt = Vt({value});").unwrap();
            } else {
                writeln!(out, "    pub const {name}: u16 = {value};").unwrap();
            }
        }
        if module == "x86" {
            // The instructions among them by number, for whoever names a
            // machine node.
            let mut named: Vec<_> = ids
                .0
                .iter()
                .filter(|(n, _)| n.starts_with(prefix) && extras.contains(n))
                .filter(|(n, _)| instructions.contains(&n[prefix.len()..]))
                .map(|(n, v)| (*v, &n[prefix.len()..]))
                .collect();
            named.sort();
            writeln!(
                out,
                "    /// The extras that are instructions, by number.\n    pub const NAMES: &[(u16, &str)] = &["
            )
            .unwrap();
            for (value, name) in named {
                writeln!(out, "        ({value}, {name:?}),").unwrap();
            }
            writeln!(out, "    ];").unwrap();
        }
        writeln!(out, "}}").unwrap();
    }
    // The pin's number of an `X86ISD::` node by its name: the builders spell
    // their own target codes and name them.
    writeln!(out, "\n/// The pin's number of the `X86ISD::<name>` node.\npub fn x86isd_id(name: &str) -> Option<u16> {{\n    Some(match name {{").unwrap();
    let mut x86isd: Vec<_> = ids.0.iter().filter(|(n, _)| n.starts_with("X86ISD::")).collect();
    x86isd.sort();
    for (name, value) in x86isd {
        writeln!(out, "        {:?} => {value},", &name["X86ISD::".len()..]).unwrap();
    }
    writeln!(out, "        _ => return None,\n    }})\n}}").unwrap();
    out
}

/// `ids.rs` of a target crate: `isd` its node opcodes (`isd` prefix), `opcode`
/// the instructions and `reg` the other `ns` names (registers), by number;
/// `generic` the `ISD::` symbols its record asks for.
pub fn render_target(
    ids: &Ids,
    isd: &str,
    ns: &str,
    instructions: &std::collections::BTreeSet<String>,
    extras: &[String],
    registers: &[String],
) -> Result<String, String> {
    let mut out = String::from(
        "//! The pin's numbers for the target's node opcodes, instructions and registers.\n//!\n//! Generated by `tools/dagisel/regen-target.sh`; do not edit.\n\n#![allow(non_upper_case_globals)]\n",
    );
    for (module, prefix) in [("isd", isd), ("opcode", ns), ("reg", ns), ("generic", "ISD::")] {
        writeln!(out, "\npub mod {module} {{").unwrap();
        let mut names: Vec<_> = ids.0.iter().filter(|(n, _)| n.starts_with(prefix)).collect();
        names.sort();
        for (name, value) in names {
            let short = &name[prefix.len()..];
            let wanted = match module {
                "opcode" => instructions.contains(short),
                "reg" => !instructions.contains(short),
                "generic" => extras.contains(name),
                _ => true,
            };
            if wanted {
                writeln!(out, "    pub const {}: u16 = {value};", constant_name(short)).unwrap();
            }
        }
        if module == "reg" && !registers.is_empty() {
            writeln!(out, "    /// The record's `registers`, by number.\n    pub const REGISTERS: &[(u16, &str)] = &[").unwrap();
            let mut named = registers.iter().map(|r| Ok((ids.get(&format!("{ns}{r}"))? as u16, r))).collect::<Result<Vec<_>, String>>()?;
            named.sort();
            for (value, name) in named {
                writeln!(out, "        ({value}, {name:?}),").unwrap();
            }
            writeln!(out, "    ];").unwrap();
        }
        writeln!(out, "}}").unwrap();
    }
    Ok(out)
}
