//! `llrm-dagisel-gen --inc X86GenDAGISel.inc --ids ids.txt --pin SHA --out DIR`
//!
//! Writes `ids.rs`, one `x86_<cpu>.rs` per CPU in `features.toml` and `mod.rs` into DIR.

use std::process::ExitCode;

use llrm_dagisel::generated::ids::mvt;
use llrm_dagisel_gen::{decode, emit, features, flatten, ids_rs, inc, prune};

const FEATURES: &str = include_str!("../features.toml");
const CPUS: [&str; 2] = ["i486", "p5"];

fn run() -> Result<(), String> {
    let mut args = std::env::args().skip(1);
    let (mut inc_path, mut ids_path, mut pin, mut out, mut extras, mut memflags) = (None, None, None, None, None, None);
    while let Some(arg) = args.next() {
        match arg.as_str() {
            "--inc" => inc_path = args.next(),
            "--ids" => ids_path = args.next(),
            "--pin" => pin = args.next(),
            "--out" => out = args.next(),
            "--extras" => extras = args.next(),
            "--memflags" => memflags = args.next(),
            other => return Err(format!("unknown argument `{other}`")),
        }
    }
    let read = |p: Option<String>, what: &str| {
        let p = p.ok_or_else(|| format!("missing {what}"))?;
        std::fs::read_to_string(&p).map_err(|e| format!("{p}: {e}"))
    };
    let ids = inc::Ids::parse(&read(ids_path, "--ids")?)?;
    let parsed = inc::parse(&read(inc_path, "--inc")?, &ids)?;
    let pin = pin.ok_or("missing --pin")?;
    let out = std::path::PathBuf::from(out.ok_or("missing --out")?);

    // `getValueTypeForHwMode`: both indices are i32 outside 64-bit mode.
    let i32 = llrm_dagisel::matcher::Vt(ids.get("MVT::i32")? as u16);
    debug_assert_eq!(i32, mvt::i32);
    let decoded = decode::decode(&parsed.matcher_table, &parsed.operand_lists, &ids, &decode::HwModes(vec![i32, i32]))?;

    let write = |name: &str, text: String| {
        let path = out.join(name);
        std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))
    };
    let extras: Vec<String> = read(extras, "--extras")?.lines().map(str::to_string).collect();
    write("ids.rs", ids_rs::render(&ids, &extras))?;
    let mut modules = String::from("//! Generated by `tools/dagisel/regen.sh`; do not edit.\n\npub mod ids;\npub mod memflags;\npub use memflags::memory_flags;\n");
    let mut emitted = std::collections::BTreeSet::new();
    for cpu_name in CPUS {
        let cpu = features::Cpu::load(FEATURES, cpu_name)?;
        let mut pruner = prune::Pruner::new(&cpu, &parsed.pattern_predicates, &ids)?;
        let kept = pruner.prune(&decoded.root);
        let flat = flatten::flatten(&kept, &decoded.lists);
        let source = emit::Source {
            cpu_name,
            cpu: &cpu,
            pin: &pin,
            flat: &flat,
            ids: &ids,
            open: &pruner.open,
            node_predicates: &parsed.node_predicates,
            complex_patterns: &parsed.complex_patterns,
            xforms: &parsed.xforms,
        };
        emitted.extend(flat.items.iter().filter_map(|m| match m {
            llrm_dagisel::matcher::Matcher::EmitNode(e) | llrm_dagisel::matcher::Matcher::MorphNodeTo(e) => Some(e.opcode),
            _ => None,
        }));
        write(&format!("x86_{cpu_name}.rs"), emit::render(&source)?)?;
        modules.push_str(&format!("pub mod x86_{cpu_name};\n"));
        eprintln!("{cpu_name}: {} items, {} operand entries", flat.items.len(), flat.operands.len());
    }
    write("memflags.rs", emit::render_memory_flags(&read(memflags, "--memflags")?, &emitted)?)?;
    write("mod.rs", modules)
}

fn main() -> ExitCode {
    match run() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("llrm-dagisel-gen: {e}");
            ExitCode::FAILURE
        }
    }
}
