//! `--target RECORD`: the tables of one non-x86 target.
//!
//! The record (`crates/target/llrm-<t>/dagisel.toml`) names the target's
//! namespaces and CPUs in `[target]`, and states the CPU, atom and predicate
//! tables in `features.toml`'s format. The output goes to the target's crate:
//! `ids.rs`, `instrinfo.rs`, one `<name>_<cpu>.rs` per CPU and `mod.rs`.

use std::collections::BTreeSet;
use std::path::Path;

use llrm_dagisel::matcher::{Matcher, Vt};

use crate::features::Cpu;
use crate::{decode, emit, flatten, ids_rs, inc, prune};

/// The `[target]` table of a record.
struct Target {
    name: String,
    /// The namespace of machine opcodes and registers (`M68k::`).
    ns: String,
    /// The prefix of the target's node opcodes (`M68kISD::`).
    isd: String,
    cpus: Vec<String>,
    /// `ByHwMode` types by mode (`getValueTypeForHwMode`), as `MVT` names.
    hw_modes: Vec<String>,
    /// Symbols the target's hand code names (`ISD::ATOMIC_CMP_SWAP`,
    /// `M68k::PC`).
    extra_symbols: Vec<String>,
    /// Registers the target's hand code maps by name (`X0`), without `ns`;
    /// written as `reg::REGISTERS`.
    registers: Vec<String>,
}

fn strings(
    table: &toml::Table,
    key: &str,
) -> Result<Vec<String>, String> {
    let Some(value) = table.get(key) else { return Ok(Vec::new()) };
    let list = value.as_array().ok_or_else(|| format!("[target] {key} is not a list"))?;
    list.iter().map(|v| v.as_str().map(str::to_string).ok_or_else(|| format!("[target] {key}: not a string"))).collect()
}

fn string(
    table: &toml::Table,
    key: &str,
) -> Result<String, String> {
    table.get(key).and_then(|v| v.as_str()).map(str::to_string).ok_or_else(|| format!("[target] has no `{key}`"))
}

impl Target {
    fn parse(text: &str) -> Result<Target, String> {
        let doc: toml::Table = text.parse().map_err(|e| format!("record: {e}"))?;
        let table = doc.get("target").and_then(|t| t.as_table()).ok_or("record has no [target]")?;
        let target = Target {
            name: string(table, "name")?,
            ns: string(table, "ns")?,
            isd: string(table, "isd")?,
            cpus: strings(table, "cpus")?,
            hw_modes: strings(table, "hw_modes")?,
            extra_symbols: strings(table, "extra_symbols")?,
            registers: strings(table, "registers")?,
        };
        // The name prefixes the generated modules (`<name>_<cpu>`).
        let mut chars = target.name.chars();
        if !chars.next().is_some_and(|c| c.is_ascii_lowercase() || c == '_')
            || !chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
        {
            return Err(format!("[target] name `{}` is not a Rust module name", target.name));
        }
        if target.cpus.is_empty() {
            return Err("[target] cpus is empty".into());
        }
        Ok(target)
    }
}

pub struct Inputs<'a> {
    pub record: &'a Path,
    pub inc: &'a str,
    pub ids: &'a str,
    pub pin: &'a str,
    pub instrinfo: &'a str,
    pub out: &'a Path,
}

pub fn run(inputs: &Inputs) -> Result<(), String> {
    let text = std::fs::read_to_string(inputs.record).map_err(|e| format!("{}: {e}", inputs.record.display()))?;
    let target = Target::parse(&text)?;
    let ids = inc::Ids::parse(inputs.ids)?;
    let parsed = inc::parse(inputs.inc, &ids)?;
    let hw = decode::HwModes(
        target
            .hw_modes
            .iter()
            .map(|name| ids.get(&format!("MVT::{name}")).map(|v| Vt(v as u16)))
            .collect::<Result<_, _>>()?,
    );
    let decoded = decode::decode(&parsed.matcher_table, &parsed.operand_lists, &ids, &hw)?;
    let instructions: BTreeSet<String> =
        inputs.instrinfo.lines().filter_map(|l| l.split(' ').next()).map(str::to_string).collect();
    let style = emit::Style {
        dagisel: "llrm_dagisel",
        predicates: "crate::dagisel::predicates",
        ns: leak(target.ns.clone()),
        title: leak(target.name.clone()),
        regen: "tools/dagisel/regen-target.sh",
        desc: "desc",
        local_desc: true,
    };
    let write = |name: &str, text: String| {
        let path = inputs.out.join(name);
        std::fs::write(&path, text).map_err(|e| format!("{}: {e}", path.display()))
    };
    let mut modules = String::from(
        "//! Generated by `tools/dagisel/regen-target.sh`; do not edit.\n\npub mod ids;\npub mod instrinfo;\n",
    );
    let mut emitted = BTreeSet::new();
    for cpu_name in &target.cpus {
        let cpu = Cpu::load(&text, cpu_name)?;
        let mut pruner = prune::Pruner::new(&cpu, &parsed.pattern_predicates, &ids)?;
        let kept = pruner.prune(&decoded.root);
        let flat = flatten::flatten(&kept, &decoded.lists);
        let source = emit::Source {
            style: &style,
            cpu_name,
            cpu: &cpu,
            pin: inputs.pin,
            flat: &flat,
            ids: &ids,
            open: &pruner.open,
            node_predicates: &parsed.node_predicates,
            complex_patterns: &parsed.complex_patterns,
            xforms: &parsed.xforms,
            instructions: &instructions,
            extra: &target.extra_symbols,
        };
        emitted.extend(flat.items.iter().filter_map(|m| match m {
            Matcher::EmitNode(e) | Matcher::MorphNodeTo(e) => Some(e.opcode),
            _ => None,
        }));
        let module = format!("{}_{cpu_name}", target.name);
        write(&format!("{module}.rs"), emit::render(&source)?)?;
        modules.push_str(&format!("pub mod {module};\n"));
        eprintln!("{cpu_name}: {} items, {} operand entries", flat.items.len(), flat.operands.len());
    }
    write(
        "ids.rs",
        ids_rs::render_target(&ids, &target.isd, &target.ns, &instructions, &target.extra_symbols, &target.registers)?,
    )?;
    write("instrinfo.rs", emit::render_instr_info(inputs.instrinfo, &ids, &emitted, &style)?)?;
    write("mod.rs", modules)
}

/// `Style` holds `&'static str`; a run makes a handful of these.
fn leak(s: String) -> &'static str {
    Box::leak(s.into_boxed_str())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn record(name: &str) -> String {
        format!("[target]\nname = \"{name}\"\nns = \"X::\"\nisd = \"XISD::\"\ncpus = [\"a\"]\n")
    }

    /// `name = "6502"` produced `pub mod 6502_mos6502;`, which does not
    /// compile.
    #[test]
    fn a_name_that_is_no_module_name_is_refused() {
        assert!(Target::parse(&record("6502")).err().unwrap().contains("module name"));
        assert!(Target::parse(&record("mos6502")).is_ok());
    }
}
